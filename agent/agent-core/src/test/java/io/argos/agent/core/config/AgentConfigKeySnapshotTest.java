package io.argos.agent.core.config;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * T-API-009, agent part (O-R03, 19 §9 "config-keys.snapshot"): the agent's configuration keys are a
 * public contract. {@code agent-config-keys.txt} lists every PUBLIC and DIAGNOSTIC key of {@link
 * ConfigKeys} with its type, documented default, remote column, kind and environment variable; this
 * test fails when a key disappears, is renamed, changes any of these, or is added without updating
 * the file. {@code AgentConfigDocTest} only keeps the registry and {@code docs/agent-config.md} in
 * step (changing both passes it); this snapshot is what makes such a change visible.
 *
 * <p>TEST keys ({@code argos.test.*}, {@code argos.testing.*}) are development-build only and are
 * not part of the contract. The file is changed by hand, in the same change as the key, never
 * regenerated by a test.
 */
@Tag("req:O-R03")
@Tag("req:T-API-009")
class AgentConfigKeySnapshotTest {

  static final String SNAPSHOT = "/config/agent-config-keys.txt";
  static final String SNAPSHOT_PATH = "agent/agent-core/src/test/resources" + SNAPSHOT;

  /** Column count of a snapshot line: key, type, default, remote, kind, env. */
  static final int COLUMNS = 6;

  /** The rendering of a key without a default ({@link KeySpec#defaultValue()} null). */
  static final String NO_DEFAULT = "(none)";

  /** The env column of keys that no environment variable sets (families, property-only keys). */
  static final String NO_ENVIRONMENT = "-";

  /** The key lines of the snapshot, in file order (comments and blank lines skipped). */
  private static List<String> snapshotLines() throws IOException {
    List<String> lines = new ArrayList<String>();
    InputStream in = AgentConfigKeySnapshotTest.class.getResourceAsStream(SNAPSHOT);
    assertThat(in).as(SNAPSHOT_PATH + " on the test class path").isNotNull();
    try (BufferedReader reader =
        new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
      String line;
      while ((line = reader.readLine()) != null) {
        String l = stripTrailing(line);
        if (!l.isEmpty() && !l.startsWith("#")) {
          lines.add(l);
        }
      }
    }
    return lines;
  }

  private static String stripTrailing(String line) {
    int end = line.length();
    while (end > 0 && Character.isWhitespace(line.charAt(end - 1))) {
      end--;
    }
    return line.substring(0, end);
  }

  private static String keyOf(String line) {
    int tab = line.indexOf('\t');
    return tab < 0 ? line : line.substring(0, tab);
  }

  private static Map<String, String> snapshot() throws IOException {
    Map<String, String> lines = new LinkedHashMap<String, String>();
    for (String line : snapshotLines()) {
      lines.put(keyOf(line), line);
    }
    return lines;
  }

  /** True for the keys of the contract: PUBLIC and DIAGNOSTIC, not TEST. */
  static boolean inContract(KeySpec spec) {
    return spec.kind() != KeySpec.Kind.TEST;
  }

  /**
   * One snapshot line: {@code key<TAB>type<TAB>default<TAB>remote<TAB>kind<TAB>env}. An ENUM type
   * carries its values ({@code enum(a|b)}), a key without default is {@code (none)}, an empty
   * default is {@code ""}, remote is {@code Y}, {@code N} or {@code -}.
   */
  static String line(KeySpec spec) {
    StringBuilder type = new StringBuilder(spec.type().name().toLowerCase(Locale.ROOT));
    if (spec.type() == KeySpec.Type.ENUM) {
      type.append('(');
      List<String> values = spec.enumValues();
      for (int i = 0; i < values.size(); i++) {
        type.append(i == 0 ? "" : "|").append(values.get(i));
      }
      type.append(')');
    }
    String defaultValue = spec.defaultValue();
    String shownDefault =
        defaultValue == null ? NO_DEFAULT : defaultValue.isEmpty() ? "\"\"" : defaultValue;
    String remote = spec.remote() == KeySpec.Remote.NONE ? "-" : spec.remote().name();
    return spec.name()
        + '\t'
        + type
        + '\t'
        + shownDefault
        + '\t'
        + remote
        + '\t'
        + spec.kind().name().toLowerCase(Locale.ROOT)
        + '\t'
        + environment(spec);
  }

  /**
   * The environment variable that sets {@code spec} ({@code ConfigLoader}): {@link
   * ConfigKeys#environmentName(String)}, none for a family (variables cannot carry the member name)
   * and for a property-only key ({@code agent.disabled}).
   */
  static String environment(KeySpec spec) {
    return spec.isFamily() || spec.isPropertyOnly()
        ? NO_ENVIRONMENT
        : ConfigKeys.environmentName(spec.name());
  }

  /** The current lines of {@code specs} in the contract, sorted by key. */
  static Map<String, String> render(List<KeySpec> specs) {
    Map<String, String> sorted = new TreeMap<String, String>();
    for (KeySpec spec : specs) {
      if (inContract(spec)) {
        sorted.put(spec.name(), line(spec));
      }
    }
    return new LinkedHashMap<String, String>(sorted);
  }

  @Test
  @DisplayName(
      "T-API-009 agent config keys: name, type, default, remote, kind and environment variable of"
          + " every PUBLIC and DIAGNOSTIC key match agent-config-keys.txt")
  void keysMatchSnapshot() throws IOException {
    Map<String, String> actual = render(ConfigKeys.all());
    List<String> diff = diff(snapshot(), actual);
    assertThat(diff)
        .as(
            "Configuration keys are a public contract (T-API-009, O-R03). The PUBLIC and"
                + " DIAGNOSTIC keys of ConfigKeys differ from %s:%n%s%n%nA removed, renamed or"
                + " retyped key, a changed default, remote column or environment variable breaks"
                + " operators' argos-agent.yml, -Dargos.<key> and ARGOS_<KEY> settings: keep the"
                + " old key or document the change (CHANGELOG entry, report). If the change is"
                + " intended, and for every new key, update %s in the same change, by hand"
                + " (tab-separated: key, type, default, remote, kind, env) and add a CHANGELOG"
                + " entry. The complete current list:%n%s",
            SNAPSHOT_PATH,
            String.join("\n", diff),
            SNAPSHOT_PATH,
            String.join("\n", actual.values()))
        .isEmpty();
  }

  /** Readable differences between the snapshot lines and the current lines, keyed by key. */
  static List<String> diff(Map<String, String> expected, Map<String, String> actual) {
    List<String> diff = new ArrayList<String>();
    for (Map.Entry<String, String> entry : expected.entrySet()) {
      String line = entry.getValue();
      String now = actual.get(entry.getKey());
      if (now == null) {
        diff.add("- " + line.replace('\t', ' ') + "    (removed or renamed)");
      } else if (!now.equals(line)) {
        diff.add("- " + line.replace('\t', ' '));
        diff.add(
            "+ " + now.replace('\t', ' ') + "    (type, default, remote, kind or env changed)");
      }
    }
    for (Map.Entry<String, String> entry : actual.entrySet()) {
      if (!expected.containsKey(entry.getKey())) {
        diff.add("+ " + entry.getValue().replace('\t', ' ') + "    (new key)");
      }
    }
    return diff;
  }

  @Test
  @DisplayName(
      "T-API-009 a removed, renamed, retyped, re-defaulted or remote-changed key and an unlisted"
          + " new key are each reported; TEST keys are not part of the contract")
  void diffReportsEveryChange() {
    List<KeySpec> before =
        Arrays.asList(
            KeySpec.builder("a.kept", KeySpec.Type.INT).defaultValue("1").build(),
            KeySpec.builder("b.removed", KeySpec.Type.BOOL).defaultValue("true").build(),
            KeySpec.builder("c.old-name", KeySpec.Type.STRING).build(),
            KeySpec.builder("d.default", KeySpec.Type.INT).defaultValue("10").build(),
            KeySpec.builder("e.type", KeySpec.Type.INT).defaultValue("5").build(),
            KeySpec.builder("f.remote", KeySpec.Type.BOOL)
                .defaultValue("false")
                .remote(KeySpec.Remote.Y)
                .build(),
            KeySpec.builder("g.enum", KeySpec.Type.ENUM)
                .defaultValue("on")
                .values("on", "off")
                .build());
    List<KeySpec> after =
        Arrays.asList(
            KeySpec.builder("a.kept", KeySpec.Type.INT).defaultValue("1").build(),
            KeySpec.builder("c.new-name", KeySpec.Type.STRING).build(),
            KeySpec.builder("d.default", KeySpec.Type.INT).defaultValue("20").build(),
            KeySpec.builder("e.type", KeySpec.Type.LONG).defaultValue("5").build(),
            KeySpec.builder("f.remote", KeySpec.Type.BOOL)
                .defaultValue("false")
                .remote(KeySpec.Remote.N)
                .build(),
            KeySpec.builder("g.enum", KeySpec.Type.ENUM).defaultValue("on").values("on").build(),
            KeySpec.builder("h.added", KeySpec.Type.LIST).defaultValue("").build(),
            KeySpec.builder("test.hook", KeySpec.Type.BOOL)
                .defaultValue("false")
                .kind(KeySpec.Kind.TEST)
                .build());
    assertThat(diff(render(before), render(after)))
        .containsExactly(
            "- b.removed bool true - public ARGOS_B_REMOVED    (removed or renamed)",
            "- c.old-name string (none) - public ARGOS_C_OLD_NAME    (removed or renamed)",
            "- d.default int 10 - public ARGOS_D_DEFAULT",
            "+ d.default int 20 - public ARGOS_D_DEFAULT    (type, default, remote, kind or env"
                + " changed)",
            "- e.type int 5 - public ARGOS_E_TYPE",
            "+ e.type long 5 - public ARGOS_E_TYPE    (type, default, remote, kind or env changed)",
            "- f.remote bool false Y public ARGOS_F_REMOTE",
            "+ f.remote bool false N public ARGOS_F_REMOTE    (type, default, remote, kind or env"
                + " changed)",
            "- g.enum enum(on|off) on - public ARGOS_G_ENUM",
            "+ g.enum enum(on) on - public ARGOS_G_ENUM    (type, default, remote, kind or env"
                + " changed)",
            "+ c.new-name string (none) - public ARGOS_C_NEW_NAME    (new key)",
            "+ h.added list \"\" - public ARGOS_H_ADDED    (new key)");
    assertThat(diff(render(before), render(before))).isEmpty();
  }

  @Test
  @DisplayName(
      "T-API-009 the env column is the real mapping: none for a family or a property-only key,"
          + " a diagnostic key keeps its kind")
  void environmentAndKindColumns() {
    assertThat(
            line(
                KeySpec.builder("x.services.*", KeySpec.Type.INT).remote(KeySpec.Remote.Y).build()))
        .isEqualTo("x.services.*\tint\t(none)\tY\tpublic\t-");
    assertThat(
            line(
                KeySpec.builder("agent.off", KeySpec.Type.BOOL)
                    .defaultValue("false")
                    .propertyOnly()
                    .build()))
        .isEqualTo("agent.off\tbool\tfalse\t-\tpublic\t-");
    assertThat(
            line(
                KeySpec.builder("debug.some-thing", KeySpec.Type.PATH)
                    .kind(KeySpec.Kind.DIAGNOSTIC)
                    .build()))
        .isEqualTo("debug.some-thing\tpath\t(none)\t-\tdiagnostic\tARGOS_DEBUG_SOME_THING");
    // The registry's own property-only key and the fixed names around the keys.
    assertThat(line(ConfigKeys.spec(ConfigKeys.AGENT_DISABLED))).endsWith("\t-");
    assertThat(ConfigKeys.PROPERTY_PREFIX).isEqualTo("argos.");
    assertThat(ConfigKeys.ENVIRONMENT_PREFIX).isEqualTo("ARGOS_");
    assertThat(ConfigKeys.TOKEN_ENVIRONMENT).isEqualTo("ARGOS_TOKEN");
    assertThat(ConfigInputs.CONFIG_ENVIRONMENT).isEqualTo("ARGOS_CONFIG");
    assertThat(ConfigInputs.DEFAULT_FILE_NAME).isEqualTo("argos-agent.yml");
  }

  @Test
  @DisplayName(
      "T-API-009 only test.* and testing.* keys are left out of the snapshot, and it is sorted,"
          + " unique, six columns per line with distinct environment variables")
  void snapshotWellFormed() throws IOException {
    for (KeySpec spec : ConfigKeys.all()) {
      assertThat(inContract(spec))
          .as("%s: kind TEST exactly for the test-only namespaces", spec.name())
          .isEqualTo(!ConfigKeys.isTestOnly(spec.name()));
    }
    List<String> lines = snapshotLines();
    List<String> keys = new ArrayList<String>();
    Set<String> environments = new HashSet<String>();
    for (String line : lines) {
      keys.add(keyOf(line));
      String[] columns = line.split("\t", -1);
      assertThat(columns).as("%s: key, type, default, remote, kind, env", line).hasSize(COLUMNS);
      assertThat(columns[3]).as(line).isIn("Y", "N", "-");
      assertThat(columns[4]).as(line).isIn("public", "diagnostic");
      if (!columns[5].equals(NO_ENVIRONMENT)) {
        assertThat(environments.add(columns[5]))
            .as("%s: environment variable unique", line)
            .isTrue();
      }
    }
    assertThat(keys)
        .isSorted()
        .doesNotHaveDuplicates()
        .noneMatch(k -> ConfigKeys.isTestOnly(k) || k.startsWith(ConfigKeys.PROPERTY_PREFIX));
  }
}
