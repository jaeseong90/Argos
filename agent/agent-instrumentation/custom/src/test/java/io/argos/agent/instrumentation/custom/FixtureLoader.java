package io.argos.agent.instrumentation.custom;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;

/**
 * A child-first class loader for the {@code example.*} fixture classes of the test sources: every
 * instance defines its own copies, so each test's classes are defined (and transformed by the
 * installed custom module) under the policy that test installed. Everything else comes from the
 * test class loader, which plays the agent class loader and is never instrumented. {@link #define}
 * defines generated bytes (the 501-class test).
 */
final class FixtureLoader extends ClassLoader {
  FixtureLoader() {
    super(FixtureLoader.class.getClassLoader());
  }

  @Override
  protected Class<?> loadClass(String name, boolean resolve) throws ClassNotFoundException {
    if (!name.startsWith("example.")) {
      return super.loadClass(name, resolve);
    }
    synchronized (getClassLoadingLock(name)) {
      Class<?> loaded = findLoadedClass(name);
      if (loaded == null) {
        byte[] bytes = read(name);
        loaded = defineClass(name, bytes, 0, bytes.length);
      }
      if (resolve) {
        resolveClass(loaded);
      }
      return loaded;
    }
  }

  /** Defines {@code name} from {@code bytes} in this loader. */
  Class<?> define(String name, byte[] bytes) {
    return defineClass(name, bytes, 0, bytes.length);
  }

  /** A new instance of the fixture class {@code name} (public no-argument constructor). */
  Object instance(String name) throws Exception {
    return loadClass(name).getConstructor().newInstance();
  }

  private byte[] read(String name) throws ClassNotFoundException {
    String resource = name.replace('.', '/') + ".class";
    try (InputStream in = getParent().getResourceAsStream(resource)) {
      if (in == null) {
        throw new ClassNotFoundException(name);
      }
      ByteArrayOutputStream out = new ByteArrayOutputStream();
      byte[] buffer = new byte[8192];
      for (int n = in.read(buffer); n >= 0; n = in.read(buffer)) {
        out.write(buffer, 0, n);
      }
      return out.toByteArray();
    } catch (IOException e) {
      throw new ClassNotFoundException(name, e);
    }
  }
}
