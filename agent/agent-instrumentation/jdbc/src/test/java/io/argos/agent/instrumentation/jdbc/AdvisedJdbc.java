package io.argos.agent.instrumentation.jdbc;

import static net.bytebuddy.matcher.ElementMatchers.isAbstract;
import static net.bytebuddy.matcher.ElementMatchers.isDefaultMethod;

import java.lang.reflect.InvocationHandler;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.lang.reflect.Proxy;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.atomic.AtomicInteger;
import javax.sql.DataSource;
import net.bytebuddy.ByteBuddy;
import net.bytebuddy.description.method.MethodDescription;
import net.bytebuddy.description.modifier.Visibility;
import net.bytebuddy.dynamic.DynamicType;
import net.bytebuddy.dynamic.loading.ClassLoadingStrategy;
import net.bytebuddy.implementation.InvocationHandlerAdapter;
import net.bytebuddy.implementation.SuperMethodCall;
import net.bytebuddy.matcher.ElementMatcher;

/**
 * JDBC classes for the advice tests: real classes (not JDK proxies) implementing {@link
 * DataSource}, {@link Connection}, {@link PreparedStatement} (and so {@link Statement}) and {@link
 * ResultSet}, generated by ByteBuddy with the module's advice inlined exactly as the agent does
 * (same advice classes, same method matchers of {@link JdbcInstrumentation}), every method handed
 * to an {@link InvocationHandler}.
 *
 * <p>A {@linkplain #driver fake driver} answers like a database (rows, update counts, URL, a
 * failure when asked); {@linkplain #pool wrapping layers} delegate every call and wrap the
 * connections, statements and result sets they return, like a pool proxy or a driver wrapper (ADR
 * -0004 C-40); {@linkplain #routing routing layers} hand the connection of the data source below
 * through unchanged, like Spring's routing data sources. Every layer is advised, so nested calls
 * run through several advised methods.
 */
final class AdvisedJdbc {
  static final String URL = "jdbc:h2:mem:shop;DB_CLOSE_DELAY=-1;USER=sa;PASSWORD=secret";

  /** DB_TARGET text of {@link #URL} (credentials and parameters removed). */
  static final String TARGET = "h2:mem:shop";

  private static final Class<? extends DataSource> DATA_SOURCE =
      generate(DataSource.class, Rule.DATA_SOURCE);
  private static final Class<? extends Connection> CONNECTION =
      generate(Connection.class, Rule.CONNECTION);
  private static final Class<? extends PreparedStatement> STATEMENT =
      generate(PreparedStatement.class, Rule.STATEMENT);
  private static final Class<? extends ResultSet> RESULT_SET =
      generate(ResultSet.class, Rule.RESULT_SET);

  private enum Rule {
    DATA_SOURCE,
    CONNECTION,
    STATEMENT,
    RESULT_SET
  }

  private AdvisedJdbc() {}

  /**
   * Two steps, like a real driver: a concrete class implementing {@code api} (every method calls
   * the handler), then a subclass that overrides the advised methods with a super call and carries
   * the inlined advice (advice applies to concrete methods, as on real JDBC classes).
   */
  private static <T> Class<? extends T> generate(Class<T> api, Rule rule) {
    ClassLoader loader = AdvisedJdbc.class.getClassLoader();
    Class<? extends T> base =
        new ByteBuddy()
            .subclass(api)
            .defineField("handler", InvocationHandler.class, Visibility.PUBLIC)
            .method(isAbstract().or(isDefaultMethod()))
            .intercept(InvocationHandlerAdapter.toField("handler"))
            .make()
            .load(loader, ClassLoadingStrategy.Default.WRAPPER)
            .getLoaded();
    DynamicType.Builder<? extends T> builder = new ByteBuddy().subclass(base);
    switch (rule) {
      case DATA_SOURCE:
        builder =
            advise(
                builder, JdbcInstrumentation.getConnection(), DataSourceGetConnectionAdvice.class);
        break;
      case CONNECTION:
        builder = advise(builder, JdbcInstrumentation.prepare(), PrepareStatementAdvice.class);
        builder =
            advise(builder, JdbcInstrumentation.commitOrRollback(), CommitRollbackAdvice.class);
        builder = advise(builder, JdbcInstrumentation.setAutoCommit(), AutoCommitGuardAdvice.class);
        break;
      case STATEMENT:
        builder =
            advise(
                builder,
                JdbcInstrumentation.preparedExecute(),
                PreparedStatementExecuteAdvice.class);
        builder =
            advise(builder, JdbcInstrumentation.statementExecute(), StatementExecuteAdvice.class);
        builder = advise(builder, JdbcInstrumentation.addBatchSql(), AddBatchSqlAdvice.class);
        builder = advise(builder, JdbcInstrumentation.statementState(), StatementStateAdvice.class);
        builder = advise(builder, JdbcInstrumentation.getResultSet(), GetResultSetAdvice.class);
        builder = advise(builder, JdbcInstrumentation.setParameter(), SetParameterAdvice.class);
        break;
      default:
        builder = advise(builder, JdbcInstrumentation.next(), ResultSetNextAdvice.class);
        builder = advise(builder, JdbcInstrumentation.close(), ResultSetCloseAdvice.class);
        break;
    }
    return builder
        .make()
        .load(base.getClassLoader(), ClassLoadingStrategy.Default.WRAPPER)
        .getLoaded();
  }

  private static <T> DynamicType.Builder<T> advise(
      DynamicType.Builder<T> builder,
      ElementMatcher<? super MethodDescription> methods,
      Class<?> advice) {
    return builder
        .method(methods)
        .intercept(SuperMethodCall.INSTANCE)
        .visit(TestAdvice.of(advice, JdbcModule.MODULE_ID).on(methods));
  }

  private static <T> T instance(Class<? extends T> type, InvocationHandler handler) {
    try {
      T value = type.getDeclaredConstructor().newInstance();
      type.getField("handler").set(value, handler);
      return value;
    } catch (ReflectiveOperationException e) {
      throw new IllegalStateException(e);
    }
  }

  // --- the fake driver -------------------------------------------------------------------------

  /** What the fake driver does and what it saw. */
  static final class Driver {
    /** {@code getMetaData()} calls on driver connections. */
    final AtomicInteger metaDataCalls = new AtomicInteger();

    /** Rows of every result set. */
    volatile int rows = 3;

    /** Thrown by {@code execute*} when set. */
    volatile SQLException executeFailure;

    /** Thrown by {@code commit} and {@code rollback} when set. */
    volatile SQLException commitFailure;

    /** Thrown by {@code getConnection} when set. */
    volatile SQLException connectFailure;

    /** Sleep of each {@code execute*} and each {@code next()}, in milliseconds. */
    volatile int executeMillis;

    volatile int nextMillis;

    /** Arguments of {@code set*} calls the driver statements received (values as given). */
    final List<Object> setValues = new CopyOnWriteArrayList<Object>();

    /** SQL the driver ran, including what a layer ran inside {@code getConnection}. */
    final List<String> executed = new CopyOnWriteArrayList<String>();

    /** SQL a driver data source runs inside {@code getConnection} (a pool validation query). */
    volatile String validationQuery;

    /**
     * When set, {@code setAutoCommit(true)} of a driver connection calls the connection's own
     * public {@code commit()}, as H2 and pgjdbc do.
     */
    volatile boolean commitInSetAutoCommit;

    /** {@code commit()} calls the driver connections received, including their own. */
    final AtomicInteger commits = new AtomicInteger();
  }

  /** A driver data source of {@code driver}. */
  static DataSource driver(final Driver driver) {
    return instance(
        DATA_SOURCE,
        new InvocationHandler() {
          @Override
          public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
            if (method.getName().equals("getConnection")) {
              if (driver.connectFailure != null) {
                throw driver.connectFailure;
              }
              Connection connection = driverConnection(driver);
              String validation = driver.validationQuery;
              if (validation != null) {
                connection.createStatement().execute(validation);
              }
              return connection;
            }
            return defaultValue(method.getReturnType());
          }
        });
  }

  /** A driver connection of {@code driver} with URL {@link #URL}. */
  static Connection driverConnection(final Driver driver) {
    final Connection[] self = new Connection[1];
    self[0] =
        instance(
            CONNECTION,
            new InvocationHandler() {
              @Override
              public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
                String name = method.getName();
                if (name.equals("prepareStatement") || name.equals("prepareCall")) {
                  return driverStatement(driver, self[0], (String) args[0]);
                }
                if (name.equals("createStatement")) {
                  return driverStatement(driver, self[0], null);
                }
                if (name.equals("getMetaData")) {
                  driver.metaDataCalls.incrementAndGet();
                  return metaData(URL);
                }
                if ((name.equals("commit") || name.equals("rollback"))
                    && driver.commitFailure != null) {
                  throw driver.commitFailure;
                }
                if (name.equals("commit")) {
                  driver.commits.incrementAndGet();
                }
                if (name.equals("setAutoCommit")
                    && Boolean.TRUE.equals(args[0])
                    && driver.commitInSetAutoCommit) {
                  self[0].commit();
                }
                return defaultValue(method.getReturnType());
              }
            });
    return self[0];
  }

  private static PreparedStatement driverStatement(
      final Driver driver, final Connection owner, final String prepared) {
    final PreparedStatement[] self = new PreparedStatement[1];
    final ResultSet[] last = new ResultSet[1];
    self[0] =
        instance(
            STATEMENT,
            new InvocationHandler() {
              @Override
              public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
                String name = method.getName();
                if (name.startsWith("execute")) {
                  driver.executed.add(
                      args != null && args.length > 0 ? (String) args[0] : prepared);
                  if (driver.executeMillis > 0) {
                    Thread.sleep(driver.executeMillis);
                  }
                  if (driver.executeFailure != null) {
                    throw driver.executeFailure;
                  }
                  if (name.equals("executeQuery") || name.equals("execute")) {
                    last[0] = driverResultSet(driver, self[0]);
                  }
                  if (name.equals("executeQuery")) {
                    return last[0];
                  }
                  if (name.equals("execute")) {
                    return true;
                  }
                  if (name.equals("executeBatch")) {
                    return new int[] {1, 1};
                  }
                  if (name.equals("executeLargeBatch")) {
                    return new long[] {1L};
                  }
                  if (name.equals("executeUpdate")) {
                    return 1;
                  }
                  return 1L;
                }
                if (name.equals("getResultSet")) {
                  return last[0];
                }
                if (name.equals("getConnection")) {
                  return owner;
                }
                if (name.startsWith("set") && args != null && args.length >= 2) {
                  driver.setValues.add(args[1]);
                }
                return defaultValue(method.getReturnType());
              }
            });
    return self[0];
  }

  private static ResultSet driverResultSet(final Driver driver, final Statement owner) {
    final int[] remaining = {driver.rows};
    return instance(
        RESULT_SET,
        new InvocationHandler() {
          @Override
          public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
            if (method.getName().equals("next")) {
              if (driver.nextMillis > 0) {
                Thread.sleep(driver.nextMillis);
              }
              return remaining[0]-- > 0;
            }
            if (method.getName().equals("getStatement")) {
              return owner;
            }
            return defaultValue(method.getReturnType());
          }
        });
  }

  private static DatabaseMetaData metaData(final String url) {
    return (DatabaseMetaData)
        Proxy.newProxyInstance(
            AdvisedJdbc.class.getClassLoader(),
            new Class<?>[] {DatabaseMetaData.class},
            new InvocationHandler() {
              @Override
              public Object invoke(Object proxy, Method method, Object[] args) {
                if (method.getName().equals("getURL")) {
                  return url;
                }
                return defaultValue(method.getReturnType());
              }
            });
  }

  // --- layers ----------------------------------------------------------------------------------

  /**
   * A pool-like (or driver-wrapper) data source over {@code target}: every call delegates, and the
   * connections, statements and result sets it returns are wrapped in advised layer objects.
   */
  static DataSource pool(final DataSource target) {
    return instance(DATA_SOURCE, wrapping(target, null));
  }

  /** A routing data source over {@code target}: the connection below is handed through as is. */
  static DataSource routing(final DataSource target) {
    return instance(
        DATA_SOURCE,
        new InvocationHandler() {
          @Override
          public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
            return invokeTarget(method, target, args);
          }
        });
  }

  /**
   * A lazy data source over {@code target}, like Spring's {@code TransactionAwareDataSourceProxy}
   * or {@code LazyConnectionDataSourceProxy}: {@code getConnection()} returns a JDK proxy at once
   * and asks {@code target} for the real connection at the proxy's first use.
   */
  static DataSource lazy(final DataSource target) {
    return instance(
        DATA_SOURCE,
        new InvocationHandler() {
          @Override
          public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
            if (!method.getName().equals("getConnection")) {
              return invokeTarget(method, target, args);
            }
            final Connection[] real = new Connection[1];
            return Proxy.newProxyInstance(
                AdvisedJdbc.class.getClassLoader(),
                new Class<?>[] {Connection.class},
                new InvocationHandler() {
                  @Override
                  public Object invoke(Object connection, Method call, Object[] callArgs)
                      throws Throwable {
                    if (real[0] == null) {
                      real[0] = target.getConnection();
                    }
                    return invokeTarget(call, real[0], callArgs);
                  }
                });
          }
        });
  }

  /**
   * A pool over {@code target} that hands out JDK proxy connections, like Tomcat JDBC: {@code
   * getConnection()} takes the connection of {@code target} at once and returns a proxy over it.
   */
  static DataSource proxying(final DataSource target) {
    return instance(
        DATA_SOURCE,
        new InvocationHandler() {
          @Override
          public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
            if (!method.getName().equals("getConnection")) {
              return invokeTarget(method, target, args);
            }
            final Connection real = target.getConnection();
            return Proxy.newProxyInstance(
                AdvisedJdbc.class.getClassLoader(),
                new Class<?>[] {Connection.class},
                new InvocationHandler() {
                  @Override
                  public Object invoke(Object connection, Method call, Object[] callArgs)
                      throws Throwable {
                    return invokeTarget(call, real, callArgs);
                  }
                });
          }
        });
  }

  /** A pool-like connection over {@code target} (statements and result sets wrapped). */
  static Connection pool(Connection target) {
    return instance(CONNECTION, wrapping(target, null));
  }

  /**
   * Delegates to {@code target} and wraps the JDBC objects it returns; a wrapped statement's {@code
   * getConnection()} answers {@code owner}, the wrapping connection that created it.
   */
  private static InvocationHandler wrapping(final Object target, final Object owner) {
    return new InvocationHandler() {
      @Override
      public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
        if (owner != null && method.getName().equals("getConnection")) {
          return owner;
        }
        Object result = invokeTarget(method, target, args);
        if (result instanceof Connection) {
          return instance(CONNECTION, wrapping(result, null));
        }
        if (result instanceof PreparedStatement) {
          return instance(STATEMENT, wrapping(result, proxy instanceof Connection ? proxy : null));
        }
        if (result instanceof ResultSet) {
          return instance(RESULT_SET, wrapping(result, null));
        }
        return result;
      }
    };
  }

  static Object invokeTarget(Method method, Object target, Object[] args) throws Throwable {
    try {
      return method.invoke(target, args);
    } catch (InvocationTargetException e) {
      throw e.getCause();
    }
  }

  static Object defaultValue(Class<?> type) {
    if (type == boolean.class) {
      return false;
    }
    if (type == int.class) {
      return 0;
    }
    if (type == long.class) {
      return 0L;
    }
    if (type == short.class) {
      return (short) 0;
    }
    if (type == byte.class) {
      return (byte) 0;
    }
    if (type == float.class) {
      return 0f;
    }
    if (type == double.class) {
      return 0d;
    }
    // void, ResultSet and every other reference type.
    return null;
  }
}
