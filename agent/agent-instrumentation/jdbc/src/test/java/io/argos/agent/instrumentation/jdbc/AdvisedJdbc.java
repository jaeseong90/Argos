package io.argos.agent.instrumentation.jdbc;

import static net.bytebuddy.matcher.ElementMatchers.isAbstract;

import java.lang.reflect.InvocationHandler;
import java.lang.reflect.Method;
import java.lang.reflect.Proxy;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.util.concurrent.atomic.AtomicInteger;
import net.bytebuddy.ByteBuddy;
import net.bytebuddy.description.modifier.Visibility;
import net.bytebuddy.dynamic.loading.ClassLoadingStrategy;
import net.bytebuddy.implementation.InvocationHandlerAdapter;
import net.bytebuddy.implementation.SuperMethodCall;

/**
 * JDBC classes for the advice tests: real classes (not JDK proxies) that implement {@link
 * Connection} or {@link PreparedStatement}, generated by ByteBuddy with the module's advice inlined
 * exactly as the agent does (same advice classes, same method matchers), every method delegating to
 * an {@link InvocationHandler}. A "pool" connection/statement wraps a "driver" one, like HikariCP
 * over a driver, so nested calls run through two advised methods.
 */
final class AdvisedJdbc {
  static final String URL = "jdbc:h2:mem:shop;DB_CLOSE_DELAY=-1;USER=sa;PASSWORD=secret";

  private static final Class<? extends Connection> CONNECTION = generate(Connection.class, true);
  private static final Class<? extends PreparedStatement> STATEMENT =
      generate(PreparedStatement.class, false);

  /** {@code getMetaData()} calls of all driver connections. */
  static final AtomicInteger META_DATA_CALLS = new AtomicInteger();

  private AdvisedJdbc() {}

  /**
   * Two steps, like a real driver: a concrete class implementing {@code api} (every method calls
   * the handler), then a subclass that overrides the advised methods with a super call and carries
   * the inlined advice (advice applies to concrete methods, as on real JDBC classes).
   */
  private static <T> Class<? extends T> generate(Class<T> api, boolean connection) {
    ClassLoader loader = AdvisedJdbc.class.getClassLoader();
    Class<? extends T> base =
        new ByteBuddy()
            .subclass(api)
            .defineField("handler", InvocationHandler.class, Visibility.PUBLIC)
            .method(isAbstract())
            .intercept(InvocationHandlerAdapter.toField("handler"))
            .make()
            .load(loader, ClassLoadingStrategy.Default.WRAPPER)
            .getLoaded();
    net.bytebuddy.dynamic.DynamicType.Builder<? extends T> builder = new ByteBuddy().subclass(base);
    if (connection) {
      builder =
          builder
              .method(JdbcInstrumentation.prepare())
              .intercept(SuperMethodCall.INSTANCE)
              .visit(
                  TestAdvice.of(PrepareStatementAdvice.class, JdbcModule.MODULE_ID)
                      .on(JdbcInstrumentation.prepare()));
    } else {
      builder =
          builder
              .method(
                  JdbcInstrumentation.preparedExecute().or(JdbcInstrumentation.statementExecute()))
              .intercept(SuperMethodCall.INSTANCE)
              .visit(
                  TestAdvice.of(PreparedStatementExecuteAdvice.class, JdbcModule.MODULE_ID)
                      .on(JdbcInstrumentation.preparedExecute()))
              .visit(
                  TestAdvice.of(StatementExecuteAdvice.class, JdbcModule.MODULE_ID)
                      .on(JdbcInstrumentation.statementExecute()));
    }
    return builder
        .make()
        .load(base.getClassLoader(), ClassLoadingStrategy.Default.WRAPPER)
        .getLoaded();
  }

  private static <T> T instance(Class<? extends T> type, InvocationHandler handler) {
    try {
      T value = type.getDeclaredConstructor().newInstance();
      type.getField("handler").set(value, handler);
      return value;
    } catch (ReflectiveOperationException e) {
      throw new IllegalStateException(e);
    }
  }

  /** A driver statement: execute methods answer, or throw {@code failure} when it is set. */
  static PreparedStatement driverStatement(final Connection owner, final SQLException failure) {
    return instance(
        STATEMENT,
        new InvocationHandler() {
          @Override
          public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
            String name = method.getName();
            if (name.startsWith("execute") && failure != null) {
              throw failure;
            }
            if (name.equals("getConnection")) {
              return owner;
            }
            return defaultValue(method.getReturnType());
          }
        });
  }

  /** A pool statement that delegates every call to {@code target}. */
  static PreparedStatement poolStatement(final PreparedStatement target, final Connection owner) {
    return instance(
        STATEMENT,
        new InvocationHandler() {
          @Override
          public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
            if (method.getName().equals("getConnection")) {
              return owner;
            }
            return invokeTarget(method, target, args);
          }
        });
  }

  /** A driver connection with URL {@link #URL}; its statements fail with {@code failure}. */
  static Connection driverConnection(final SQLException failure) {
    final Connection[] self = new Connection[1];
    self[0] =
        instance(
            CONNECTION,
            new InvocationHandler() {
              @Override
              public Object invoke(Object proxy, Method method, Object[] args) {
                String name = method.getName();
                if (name.equals("prepareStatement") || name.equals("createStatement")) {
                  return driverStatement(self[0], failure);
                }
                if (name.equals("getMetaData")) {
                  META_DATA_CALLS.incrementAndGet();
                  return metaData(URL);
                }
                return defaultValue(method.getReturnType());
              }
            });
    return self[0];
  }

  /** A pool connection over {@code target}; its statements wrap the driver's. */
  static Connection poolConnection(final Connection target) {
    final Connection[] self = new Connection[1];
    self[0] =
        instance(
            CONNECTION,
            new InvocationHandler() {
              @Override
              public Object invoke(Object proxy, Method method, Object[] args) throws Throwable {
                Object result = invokeTarget(method, target, args);
                if (method.getName().equals("prepareStatement")) {
                  return poolStatement((PreparedStatement) result, self[0]);
                }
                return result;
              }
            });
    return self[0];
  }

  static Object invokeTarget(Method method, Object target, Object[] args) throws Throwable {
    try {
      return method.invoke(target, args);
    } catch (java.lang.reflect.InvocationTargetException e) {
      throw e.getCause();
    }
  }

  private static DatabaseMetaData metaData(final String url) {
    return (DatabaseMetaData)
        Proxy.newProxyInstance(
            AdvisedJdbc.class.getClassLoader(),
            new Class<?>[] {DatabaseMetaData.class},
            new InvocationHandler() {
              @Override
              public Object invoke(Object proxy, Method method, Object[] args) {
                if (method.getName().equals("getURL")) {
                  return url;
                }
                return defaultValue(method.getReturnType());
              }
            });
  }

  static Object defaultValue(Class<?> type) {
    if (type == boolean.class) {
      return false;
    }
    if (type == int.class) {
      return 0;
    }
    if (type == long.class) {
      return 0L;
    }
    if (type == short.class) {
      return (short) 0;
    }
    if (type == byte.class) {
      return (byte) 0;
    }
    if (type == float.class) {
      return 0f;
    }
    if (type == double.class) {
      return 0d;
    }
    // void, ResultSet and every other reference type.
    return null;
  }
}
