package io.argos.agent.testing.launcher;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * The agent settings of one run (keys of 10 §15 without the {@code argos.} prefix) and their two
 * forms (18 §5.2 {@code withAgent(jar, argosConfig)}):
 *
 * <ul>
 *   <li>{@link #systemProperties()}: {@code -Dargos.<key>=<value>}, the form every agent build
 *       reads today;
 *   <li>{@link #yaml()}: an {@code argos-agent.yml} with the same keys as nested YAML. The agent
 *       reads YAML from WO-10 on (10 §15 ConfigLoader); until then {@code -Dargos.config} only
 *       produces the agent's "not supported yet" WARN, so the launcher writes the file only on
 *       request ({@link AppLauncher#agentConfigFile(boolean)}).
 * </ul>
 *
 * <p>Test-only keys use the {@code argos.test.*} namespace (18 §15): {@code test.exporter}, {@code
 * test.faults}. Release builds ignore them (T-BLD-010).
 */
public final class AgentSettings {
  private final Map<String, String> values = new LinkedHashMap<>();

  public AgentSettings put(String key, String value) {
    if (key.startsWith("argos.")) {
      throw new IllegalArgumentException("agent keys have no argos. prefix: " + key);
    }
    values.put(key, value);
    return this;
  }

  public AgentSettings putAll(Map<String, String> settings) {
    settings.forEach(this::put);
    return this;
  }

  public String get(String key) {
    return values.get(key);
  }

  public Map<String, String> asMap() {
    return new LinkedHashMap<>(values);
  }

  /** {@code -Dargos.<key>=<value>} in insertion order. */
  public List<String> systemProperties() {
    List<String> options = new ArrayList<>();
    values.forEach((key, value) -> options.add("-Dargos." + key + "=" + value));
    return options;
  }

  /**
   * The settings as {@code argos-agent.yml} (keys split at {@code .} into nested maps, sorted;
   * values as single-quoted YAML strings). A key that is both a value and a parent ({@code
   * server.tls} and {@code server.tls.ca-file}) is written in flat form ({@code tls.ca-file:})
   * below its parent, which YAML loaders of 10 §15 read as the same path.
   */
  public String yaml() {
    Map<String, String> sorted = new TreeMap<>(values);
    StringBuilder out = new StringBuilder("# Generated by the Argos agent test harness\n");
    writeLevel(out, sorted, "", 0);
    return out.toString();
  }

  private static void writeLevel(
      StringBuilder out, Map<String, String> all, String prefix, int depth) {
    List<String> children = new ArrayList<>();
    for (String key : all.keySet()) {
      if (!key.startsWith(prefix)) {
        continue;
      }
      String rest = key.substring(prefix.length());
      String head = rest.contains(".") ? rest.substring(0, rest.indexOf('.')) : rest;
      if (!children.contains(head)) {
        children.add(head);
      }
    }
    String indent = "  ".repeat(depth);
    for (String head : children) {
      String path = prefix + head;
      boolean leaf = all.containsKey(path);
      boolean parent = all.keySet().stream().anyMatch(k -> k.startsWith(path + "."));
      if (leaf && !parent) {
        out.append(indent).append(head).append(": ").append(quote(all.get(path))).append('\n');
      } else if (!leaf) {
        out.append(indent).append(head).append(":\n");
        writeLevel(out, all, path + ".", depth + 1);
      } else {
        // Both a value and a parent: the value stays flat at this level.
        out.append(indent).append(head).append(": ").append(quote(all.get(path))).append('\n');
        for (String key : all.keySet()) {
          if (key.startsWith(path + ".")) {
            out.append(indent)
                .append(head)
                .append(key.substring(path.length()))
                .append(": ")
                .append(quote(all.get(key)))
                .append('\n');
          }
        }
      }
    }
  }

  private static String quote(String value) {
    return "'" + value.replace("'", "''") + "'";
  }
}
