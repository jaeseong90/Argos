      // AbstractFutureState falls back to its field-updater helper (catches the linkage error).
      "com/google/common/util/concurrent/AbstractFutureState\$UnsafeAtomicHelper.class",
      "com/google/protobuf/MessageSchema.class",
      "com/google/protobuf/UnsafeUtil.class",
      "com/google/protobuf/UnsafeUtil\$1.class",
      "com/google/protobuf/UnsafeUtil\$Android32MemoryAccessor.class",
      "com/google/protobuf/UnsafeUtil\$Android64MemoryAccessor.class",
      "com/google/protobuf/UnsafeUtil\$JvmMemoryAccessor.class",
      "com/google/protobuf/UnsafeUtil\$MemoryAccessor.class",
      "io/netty/util/internal/CleanerJava9\$1.class",
      "io/netty/util/internal/CleanerJava9\$2.class",
      "io/netty/util/internal/PlatformDependent\$Mpsc\$1.class",
      "io/netty/util/internal/PlatformDependent0\$1.class",
      "io/netty/util/internal/PlatformDependent0\$2.class",
      "io/netty/util/internal/PlatformDependent0\$3.class",
      "io/netty/util/internal/PlatformDependent0\$4.class",
      "io/netty/util/internal/PlatformDependent0\$6.class",
      "io/netty/util/internal/shaded/org/jctools/queues/LinkedQueueNode.class",
      "io/netty/util/internal/shaded/org/jctools/util/UnsafeAccess.class",
      "io/netty/util/internal/shaded/org/jctools/util/UnsafeLongArrayAccess.class",
      "io/netty/util/internal/shaded/org/jctools/util/UnsafeRefArrayAccess.class",
    )

  /**
   * Group of the artifacts kept whole by Shadow's `minimize()` besides the Argos projects (ADR-0005
   * decision 5, 19 §13 #4): gRPC loads its providers (`NameResolverProvider`,
   * `LoadBalancerProvider`, ...) through ServiceLoader and `Class.forName`, which minimize cannot
   * follow. Netty, Guava and protobuf are minimized.
   */
  val MINIMIZE_ROOT_GROUPS = listOf("io.grpc")

  /**
   * Annotation-only artifacts of the gRPC, Guava and protobuf graphs (ADR-0005, P-3): never read at
   * run time (CLASS retention, or annotations nothing reflects on), so they are left out of the
   * agent entirely instead of being relocated (`javax.annotation` of jsr305 could not be relocated
   * at all).
   */
  val ANNOTATION_ONLY_MODULES =
    listOf(
      "com.google.code.findbugs" to "jsr305",
      "com.google.errorprone" to "error_prone_annotations",
      "com.google.j2objc" to "j2objc-annotations",
      "org.codehaus.mojo" to "animal-sniffer-annotations",
      "org.checkerframework" to "checker-qual",
      "com.google.android" to "annotations",
      "org.jetbrains" to "annotations",
      "org.jspecify" to "jspecify",
    )

  /**
   * The agent class that replaces `java.util.logging.Logger` in every shaded library (ADR-0005
   * decision 4): Shadow relocates the class reference, so gRPC, Netty, Guava and protobuf log
   * through the agent log (SEVERE as ERROR, WARNING as WARN, INFO as INFO, CONFIG and FINE as DEBUG)
   * and the agent never initialises the JDK `LogManager` (AGT-02, F-A35). checkJulBridge verifies
   * the result.
   */
  const val JUL_LOGGER_BRIDGE = "io.argos.agent.core.log.JulLogger"

  /** JDK logging classes that no class of the agent jar may reference (checkJulBridge, AGT-02). */
  val JUL_FORBIDDEN_CLASSES = listOf("java/util/logging/Logger", "java/util/logging/LogManager")

  /**
   * Own-class constants that are meant to be in the relocated namespace (checkOwnRelocatedLiterals,
   * ADR-0008): the Netty property names the transport sets (`NettyProps`, 10 §10.3, ADR-0005
   * decision 7), each as `<jar entry>: <constant>`.
   */
  val OWN_RELOCATED_LITERALS: List<String> =
    listOf(
        "io.netty.noUnsafe",
        "io.netty.allocator.type",
        "io.netty.noPreferDirect",
        "io.netty.maxDirectMemory",
        "io.netty.tryReflectionSetAccessible",
        "io.netty.eventLoopThreads",
        "io.netty.allocator.numDirectArenas",
        "io.netty.leakDetection.level",
        "io.netty.recycler.maxCapacityPerThread",
        "io.netty.noKeySetOptimization",
      )
      .map { "inst/io/argos/agent/core/transport/NettyProps.classdata: $PREFIX.$it" }

  /** Entries removed from the shaded jar (signatures, JPMS and multi-release metadata). */
  val EXCLUDED_ENTRIES =
    listOf(
      "META-INF/*.SF",
      "META-INF/*.DSA",
