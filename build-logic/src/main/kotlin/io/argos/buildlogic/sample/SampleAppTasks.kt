abstract class SampleSmokeSlot : BuildService<BuildServiceParameters.None>

/** Command line of io.argos.sample.smoke.SmokeMain for one smoke variant. */
abstract class SmokeArguments : CommandLineArgumentProvider {

  @get:Input abstract val appName: Property<String>

  @get:Input abstract val variantName: Property<String>

  @get:Input abstract val kind: Property<String>

  @get:Input abstract val catalog: Property<String>

  @get:InputFile
  @get:PathSensitive(PathSensitivity.NONE)
  abstract val artifact: RegularFileProperty

  @get:Nested abstract val appLauncher: Property<JavaLauncher>

  @get:Input abstract val appJdk: Property<Int>

  @get:Input abstract val environment: MapProperty<String, String>

  @get:Input abstract val jvmArgs: ListProperty<String>

  @get:Input abstract val runtimeExpectations: MapProperty<String, String>

  @get:Input abstract val bodyExpectations: MapProperty<String, String>

  @get:Input abstract val expectClients: ListProperty<String>

  @get:Input abstract val contexts: ListProperty<String>

  @get:Input abstract val seedEnvironment: Property<Boolean>

  @get:Internal abstract val tomcatHome: DirectoryProperty

  @get:Internal abstract val reportDirectory: DirectoryProperty

  @get:Input @get:Optional abstract val startupRuns: Property<String>

  @get:Input @get:Optional abstract val extStubUrl: Property<String>

  override fun asArguments(): Iterable<String> {
    val args = mutableListOf<String>()
    fun add(name: String, value: String) {
      args += name
      args += value
    }
    add("--app", appName.get())
    add("--variant", variantName.get())
    add("--kind", kind.get())
    add("--catalog", catalog.get())
    add("--artifact", artifact.get().asFile.absolutePath)
    add("--app-java", appLauncher.get().executablePath.asFile.absolutePath)
    add("--app-jdk", appJdk.get().toString())
    environment.get().toSortedMap().forEach { (k, v) -> add("--env", "$k=$v") }
    jvmArgs.get().forEach { add("--jvm-arg", it) }
    runtimeExpectations.get().toSortedMap().forEach { (k, v) -> add("--expect-runtime", "$k=$v") }
    bodyExpectations.get().toSortedMap().forEach { (k, v) -> add("--expect-body", "$k=$v") }
    val clients = expectClients.get()
    if (clients.isNotEmpty()) add("--expect-clients", clients.sorted().joinToString(","))
    contexts.get().forEach { add("--context", it) }
    if (seedEnvironment.getOrElse(false)) args += "--seed-env"
    if (tomcatHome.isPresent) add("--tomcat-home", tomcatHome.get().asFile.absolutePath)
    add("--report-dir", reportDirectory.get().asFile.absolutePath)
    if (startupRuns.isPresent) add("--startup-runs", startupRuns.get())
    if (extStubUrl.isPresent) add("--ext-stub-url", extStubUrl.get())
    return args
  }
}

/** `-Xlint:-options` for `--release 8` (JDK 21 javac reports release 8 as obsolete). */
class ObsoleteReleaseLintArgument(private val release: org.gradle.api.provider.Provider<Int>) :
  CommandLineArgumentProvider {

  @get:Input val javaRelease: Int
    get() = release.get()

  override fun asArguments(): Iterable<String> =
    if (javaRelease <= 8) listOf("-Xlint:-options") else emptyList()
}
