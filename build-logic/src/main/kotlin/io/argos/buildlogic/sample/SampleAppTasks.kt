/**
 * Writes `BOOT-INF/classpath.idx` (Spring Boot loader class path order) from the runtime class path
 * and fails on two jars with the same file name, which would overwrite each other in BOOT-INF/lib.
 */
abstract class SampleClasspathIndex : DefaultTask() {

  @get:Classpath abstract val libraries: ConfigurableFileCollection

  @get:OutputFile abstract val indexFile: RegularFileProperty

  @TaskAction
  fun write() {
    val names = libraries.files.filter { it.isFile && it.name.endsWith(".jar") }.map { it.name }
    val duplicates = names.groupingBy { it }.eachCount().filterValues { it > 1 }.keys
    if (duplicates.isNotEmpty()) {
      throw GradleException("Two runtime jars share a file name (BOOT-INF/lib): $duplicates")
    }
    indexFile.get().asFile.writeText(names.joinToString("") { "- \"BOOT-INF/lib/$it\"\n" })
  }
}

/**
 * Writes `io/argos/sample/build-info.properties` (app name and version) into a generated resource
 * directory. The apps expose it at GET /api/version (F-A21). No timestamp: archives stay
 * reproducible (19 §3.7).
 */
abstract class SampleBuildInfo : DefaultTask() {

  @get:Input abstract val appName: Property<String>

  @get:Input abstract val appVersion: Property<String>

  @get:OutputDirectory abstract val outputDirectory: DirectoryProperty

  @TaskAction
  fun write() {
    val file = File(outputDirectory.get().asFile, "io/argos/sample/build-info.properties")
    file.parentFile.mkdirs()
    file.writeText(
      "# Generated by the argos.sample-app convention plugin.\n" +
        "app=${appName.get()}\n" +
        "version=${appVersion.get()}\n"
    )
  }
}

/**
 * Writes `build/sample-app/<app>.properties`: how to start the packaged app (kind, artifact, main
 * class, JDK, catalog, WAR contexts). Read by humans and by the agent test harness (18 §5.2).
 */
abstract class SampleLaunchDescriptor : DefaultTask() {

  @get:Input abstract val properties: MapProperty<String, String>

  @get:OutputFile abstract val descriptor: RegularFileProperty

  @TaskAction
  fun write() {
    descriptor
      .get()
      .asFile
      .writeText(
        "# Generated by the argos.sample-app convention plugin (sample-apps/README.md).\n" +
          properties.get().toSortedMap().entries.joinToString("") { "${it.key}=${it.value}\n" }
      )
  }
}

