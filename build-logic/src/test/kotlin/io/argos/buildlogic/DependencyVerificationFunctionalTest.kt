package io.argos.buildlogic

import java.io.File
import java.security.MessageDigest
import org.assertj.core.api.Assertions.assertThat
import org.gradle.testkit.runner.GradleRunner
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.DisplayName
import org.junit.jupiter.api.Tag
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir

/**
 * Dependency verification is enforced (SEC-73, 16 section 10.4): Gradle refuses an artifact whose
 * checksum differs from gradle/verification-metadata.xml and an artifact that the file does not list.
 * Each test is a throwaway build in the same format as the repository's metadata (verify-metadata
 * true, sha256) that resolves one module from a local file repository (no network). The repository's
 * own metadata and the absence of lenient or off switches are checked by
 * .github/scripts/check-dependency-verification.sh (same proposed test ID).
 */
@Tag("req:SEC-73")
class DependencyVerificationFunctionalTest {
  @TempDir lateinit var project: File

  private lateinit var jarSha256: String
  private lateinit var pomSha256: String

  @BeforeEach
  fun setUp() {
    val dir = File(project, "repo/com/example/lib/1.0").apply { mkdirs() }
    val pom = File(dir, "lib-1.0.pom")
    pom.writeText(
      """<?xml version="1.0" encoding="UTF-8"?>
      <project xmlns="http://maven.apache.org/POM/4.0.0">
        <modelVersion>4.0.0</modelVersion>
        <groupId>com.example</groupId><artifactId>lib</artifactId><version>1.0</version>
      </project>
      """
        .trimIndent()
    )
    val jar = writeJar(File(dir, "lib-1.0.jar"), null, mapOf("com/example/Lib.class" to classFile("com/example/Lib")))
    jarSha256 = sha256(jar)
    pomSha256 = sha256(pom)
    File(project, "settings.gradle")
      .writeText(
        """
        dependencyResolutionManagement {
          repositories { maven { url = uri('repo') } }
        }
        rootProject.name = 'verification-fixture'
        """
          .trimIndent()
      )
    File(project, "build.gradle")
      .writeText(
        """
        plugins { id 'java-library' }
        dependencies { implementation 'com.example:lib:1.0' }
        tasks.register('resolveClasspath') {
          def classpath = configurations.compileClasspath
          inputs.files(classpath)
          doLast { println('resolved: ' + classpath.files*.name.sort().join(',')) }
        }
        """
          .trimIndent()
      )
  }

  private fun sha256(file: File): String =
    MessageDigest.getInstance("SHA-256").digest(file.readBytes()).joinToString("") { "%02x".format(it) }

  /** gradle/verification-metadata.xml of the fixture with the given component entries. */
  private fun metadata(components: String) {
    File(project, "gradle").mkdirs()
    File(project, "gradle/verification-metadata.xml")
      .writeText(
        """<?xml version="1.0" encoding="UTF-8"?>
        <verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
           <configuration>
              <verify-metadata>true</verify-metadata>
              <verify-signatures>false</verify-signatures>
           </configuration>
           <components>
        $components
           </components>
        </verification-metadata>
        """
          .trimIndent()
      )
  }

  private fun component(jar: String, pom: String) =
    """
          <component group="com.example" name="lib" version="1.0">
             <artifact name="lib-1.0.jar"><sha256 value="$jar" origin="Generated by Gradle"/></artifact>
             <artifact name="lib-1.0.pom"><sha256 value="$pom" origin="Generated by Gradle"/></artifact>
          </component>
    """
      .trimEnd()

  /** The HTML report Gradle writes on a verification failure (it names expected and actual checksums). */
  private fun reportOf(output: String): String {
    val reports =
      File(project, "build/reports/dependency-verification")
        .walkTopDown()
        .filter { it.isFile && it.name == "dependency-verification-report.html" }
        .toList()
    assertThat(reports).describedAs("dependency verification report (output: %s)", output).hasSize(1)
    return reports.single().readText()
  }

  private fun runner(): GradleRunner =
    GradleRunner.create()
      .withProjectDir(project)
      .withArguments("resolveClasspath", "--offline", "--stacktrace", "--no-configuration-cache")

  @Test
  @DisplayName("T-SEC-73a a dependency whose sha256 matches the verification metadata resolves")
  fun matchingChecksumResolves() {
    metadata(component(jarSha256, pomSha256))
    val result = runner().build()
    assertThat(result.output).contains("resolved: lib-1.0.jar")
  }

  @Test
  @DisplayName("T-SEC-73a a dependency whose sha256 differs from the verification metadata fails the build")
  fun wrongChecksumFails() {
    val wrong = jarSha256.replaceRange(0, 1, if (jarSha256[0] == '0') "1" else "0")
    metadata(component(wrong, pomSha256))
    val result = runner().buildAndFail()
    assertThat(result.output)
      .contains("Dependency verification failed for configuration ':compileClasspath'")
      .contains("One artifact failed verification: lib-1.0.jar (com.example:lib:1.0)")
      .contains("This can indicate that a dependency has been compromised")
      .doesNotContain("resolved: ")
    assertThat(reportOf(result.output)).contains(wrong).contains(jarSha256)
  }

  @Test
  @DisplayName("T-SEC-73a a tampered POM (metadata is verified too) fails the build")
  fun wrongPomChecksumFails() {
    metadata(component(jarSha256, pomSha256))
    File(project, "repo/com/example/lib/1.0/lib-1.0.pom").appendText("\n<!-- changed -->\n")
    val result = runner().buildAndFail()
    assertThat(result.output)
      .contains("Dependency verification failed for configuration ':compileClasspath'")
      .contains("One artifact failed verification: lib-1.0.pom (com.example:lib:1.0)")
      .contains("This can indicate that a dependency has been compromised")
  }

  @Test
  @DisplayName("T-SEC-73a a dependency missing from the verification metadata fails the build")
  fun missingEntryFails() {
    metadata(
      """
          <component group="com.example" name="other" version="1.0">
             <artifact name="other-1.0.jar"><sha256 value="$jarSha256" origin="Generated by Gradle"/></artifact>
          </component>
      """
        .trimEnd()
    )
    val result = runner().buildAndFail()
    assertThat(result.output)
      .contains("Dependency verification failed for configuration ':compileClasspath'")
      .contains("2 artifacts failed verification:")
      .contains("- lib-1.0.jar (com.example:lib:1.0)")
      .contains("- lib-1.0.pom (com.example:lib:1.0)")
      .contains("you will need to update the gradle/verification-metadata.xml file")
      .doesNotContain("resolved: ")
  }
}
