-- Argos PostgreSQL roles: the reference SQL of C-11 / ADR-0010 C-97 (docs/02 section 13, 13 section
-- 12, 16 section 10.8). The installer runs it once per installation and again on upgrades, as a
-- superuser connected to the Argos database; the server never runs it. WO-40 wires it into Compose
-- (a config/postgres/init script that passes the generated secrets) and into the tar installer.
--
--   psql -X -q -v ON_ERROR_STOP=1 \
--        -v owner_password="$(cat secrets/pg_owner_password)" \
--        -v app_password="$(cat secrets/pg_app_password)" \
--        -v audit_password="$(cat secrets/pg_audit_password)" \
--        -v backup_password="$(cat secrets/pg_backup_password)" \
--        [-v owner_role=argos] -U postgres -d argos -f roles.sql
--
-- Roles (LOGIN, no SUPERUSER, CREATEDB, CREATEROLE, REPLICATION or BYPASSRLS):
--   owner (default "argos", -v owner_role=...)  owns the database and the schema argos; Flyway and
--                     the ClickHouse migration history use it during the start only
--                     (argos.postgres.owner.*)
--   argos_app         server runtime (argos.postgres.user / password-file); its table privileges
--                     come from the Flyway migrations (V001): DML, audit_logs INSERT and SELECT only
--   argos_audit       audit log partition retention job (12 section 8.1)
--   argos_backup      read-only dump (13 section 10)
--
-- Passwords are psql variables only (no literal in this file), generated by the installer with a
-- CSPRNG (SEC-74); fewer than 12 characters stop the script. Statement logging is switched off for
-- this session so that no CREATE ROLE ... PASSWORD reaches the PostgreSQL log.
-- Idempotent: existing roles keep their passwords; their attributes are reset to the least
-- privilege above (except an existing owner role, which may be the bootstrap superuser of a
-- container image and is left as it is).
-- Done here (needs a superuser): the roles, ownership of the database and of the schema argos,
-- CONNECT for the roles and nothing for PUBLIC, no CREATE on schema public, the pg_trgm extension
-- in schema argos (13 section 17 item 15).

\set ON_ERROR_STOP on

SET log_statement = 'none';
SET log_min_duration_statement = -1;
SET log_min_error_statement = 'panic';

\if :{?owner_role}
\else
\set owner_role argos
\endif

\if :{?owner_password}
\else
DO $$ BEGIN RAISE EXCEPTION 'roles.sql: -v owner_password=... is required'; END $$;
\endif
\if :{?app_password}
\else
DO $$ BEGIN RAISE EXCEPTION 'roles.sql: -v app_password=... is required'; END $$;
\endif
\if :{?audit_password}
\else
DO $$ BEGIN RAISE EXCEPTION 'roles.sql: -v audit_password=... is required'; END $$;
\endif
\if :{?backup_password}
\else
DO $$ BEGIN RAISE EXCEPTION 'roles.sql: -v backup_password=... is required'; END $$;
\endif

SELECT length(:'owner_password') >= 12 AND length(:'app_password') >= 12
   AND length(:'audit_password') >= 12 AND length(:'backup_password') >= 12 AS argos_passwords_ok \gset
\if :argos_passwords_ok
\else
DO $$ BEGIN RAISE EXCEPTION 'roles.sql: every password needs at least 12 characters (SEC-74)'; END $$;
\endif

-- Roles -----------------------------------------------------------------------------------------

SELECT format('CREATE ROLE %I LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L',
              :'owner_role', :'owner_password')
 WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'owner_role') \gexec

SELECT format('CREATE ROLE %I LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L',
              r.name, r.password)
  FROM (VALUES ('argos_app', :'app_password'),
               ('argos_audit', :'audit_password'),
               ('argos_backup', :'backup_password')) AS r(name, password)
 WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r.name) \gexec

ALTER ROLE argos_app NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS LOGIN;
ALTER ROLE argos_audit NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS LOGIN;
ALTER ROLE argos_backup NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS LOGIN;

-- Database and schema ---------------------------------------------------------------------------

SELECT format('ALTER DATABASE %I OWNER TO %I', current_database(), :'owner_role') \gexec
SELECT format('REVOKE ALL ON DATABASE %I FROM PUBLIC', current_database()) \gexec
SELECT format('GRANT CONNECT ON DATABASE %I TO argos_app, argos_audit, argos_backup', current_database()) \gexec

REVOKE CREATE ON SCHEMA public FROM PUBLIC;

SELECT format('CREATE SCHEMA IF NOT EXISTS argos AUTHORIZATION %I', :'owner_role') \gexec
SELECT format('ALTER SCHEMA argos OWNER TO %I', :'owner_role') \gexec

CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA argos;
