// argos.v1 protocol definitions (11 §, 19 §3.4) and the integer protocol version in
// PROTOCOL_VERSION (DSN-19-10). The generated Java code (full protobuf-java + gRPC stubs) serves
// the agent (relocated into the agent jar), the server and the test harness (ADR-0010 C-104); it
// targets Java 8 like the agent.

import io.argos.buildlogic.argosProtocolVersion

plugins {
  id("argos.java-agent")
  id("argos.protobuf")
}

description = "Argos protocol (argos.v1 protobuf messages and gRPC services)."

// io.argos.proto.ProtocolVersion.CURRENT from proto/PROTOCOL_VERSION (19 §3.4). Build output only.
val protocolVersionDir = layout.buildDirectory.dir("generated/sources/protocolVersion/java/main")
val generateProtocolVersion =
  tasks.register("generateProtocolVersion") {
    description = "Generates io.argos.proto.ProtocolVersion from proto/PROTOCOL_VERSION."
    val version = argosProtocolVersion()
    val outputDir = protocolVersionDir
    inputs.property("protocolVersion", version)
    outputs.dir(outputDir)
    doLast {
      val file = outputDir.get().file("io/argos/proto/ProtocolVersion.java").asFile
      file.parentFile.mkdirs()
      file.writeText(
        """
        |/* SPDX-License-Identifier: Apache-2.0 */
        |package io.argos.proto;
        |
        |/**
        | * The integer argos.v1 protocol version (DSN-19-10, 11 §5 version rules). Generated by the
        | * :proto build from proto/PROTOCOL_VERSION; do not edit.
        | */
        |public final class ProtocolVersion {
        |  /** The version this build speaks ({@code AgentHello.protocol_version}). */
        |  public static final int CURRENT = ${version.get()};
        |
        |  private ProtocolVersion() {}
        |}
        |"""
          .trimMargin()
      )
    }
  }

sourceSets.named("main") { java.srcDir(generateProtocolVersion.map { protocolVersionDir }) }

dependencies {
  // Contract test (b): protocol enum numbers equal the agent bootstrap constants (C-1, C-16).
  testImplementation(project(":agent:agent-bootstrap"))
}

// The contract tests compare ProtocolVersion.CURRENT with this file (read relative to the project
// directory, the test working directory).
tasks.named<Test>("test") {
  workingDir = layout.projectDirectory.asFile
  inputs
    .file(layout.projectDirectory.file("PROTOCOL_VERSION"))
    .withPropertyName("protocolVersionFile")
    .withPathSensitivity(PathSensitivity.RELATIVE)
}
