-- Sample app schema for IBM Db2 LUW 11.1 and later (SAMPLE_DB=db2, WO-50; trusted runners only, not
-- checked by a run yet). Plain statements: ShopSchema runs each one only when the JDBC metadata does
-- not list the object yet (DbKind.createsMissingObjectsOnly). Statements end with ';' at the end of
-- a line.
CREATE TABLE customers (
  id BIGINT NOT NULL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(200) NOT NULL
);
CREATE TABLE products (
  id BIGINT NOT NULL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  price DECIMAL(12, 2) NOT NULL
);
CREATE TABLE orders (
  id BIGINT NOT NULL PRIMARY KEY,
  customer_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  amount DECIMAL(12, 2) NOT NULL,
  created_at TIMESTAMP NOT NULL
);
CREATE TABLE order_items (
  id BIGINT NOT NULL PRIMARY KEY,
  order_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  quantity INTEGER NOT NULL
);
CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE TABLE audit_log (
  id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message VARCHAR(500) NOT NULL,
  created_at TIMESTAMP NOT NULL
);
