package io.argos.sample.smoke;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;

/**
 * A CATALINA_BASE for one smoke run of a WAR app: the configuration of the staged Tomcat
 * distribution (CATALINA_HOME, build/tomcat/<key>), a server.xml with the chosen HTTP port bound to
 * 127.0.0.1 and no shutdown port, and the WAR copied once per context path ({@code shop-a.war} is
 * served under {@code /shop-a}). Tomcat is started with {@code java ... Bootstrap start} directly,
 * so the same command works on Windows and Linux.
 */
final class TomcatBase {

  private TomcatBase() {}

  static List<String> command(SmokeOptions options, Path runDir, int port) throws IOException {
    Path home = options.tomcatHome.toAbsolutePath();
    Path base = runDir.resolve("catalina-base").toAbsolutePath();
    Path conf = Files.createDirectories(base.resolve("conf"));
    Files.createDirectories(base.resolve("logs"));
    Files.createDirectories(base.resolve("temp"));
    Files.createDirectories(base.resolve("work"));
    Path webapps = Files.createDirectories(base.resolve("webapps"));
    try (DirectoryStream<Path> files = Files.newDirectoryStream(home.resolve("conf"))) {
      for (Path file : files) {
        if (Files.isRegularFile(file) && !file.getFileName().toString().equals("server.xml")) {
          Files.copy(file, conf.resolve(file.getFileName()), StandardCopyOption.REPLACE_EXISTING);
        }
      }
    }
    Files.writeString(conf.resolve("server.xml"), serverXml(port), StandardCharsets.UTF_8);
    for (String context : options.contexts) {
      String name = context.replaceAll("^/+|/+$", "");
      if (name.isEmpty()) {
        name = "ROOT";
      }
      Files.copy(
          options.artifact, webapps.resolve(name + ".war"), StandardCopyOption.REPLACE_EXISTING);
    }
    List<String> command = new ArrayList<>();
    if (options.appJdk >= 9) {
      // As catalina.sh does on JDK 9+: lets Tomcat's leak detection read JDK internals.
      command.add("--add-opens=java.base/java.lang=ALL-UNNAMED");
      command.add("--add-opens=java.base/java.io=ALL-UNNAMED");
      command.add("--add-opens=java.base/java.util=ALL-UNNAMED");
      command.add("--add-opens=java.base/java.util.concurrent=ALL-UNNAMED");
      command.add("--add-opens=java.rmi/sun.rmi.transport=ALL-UNNAMED");
    }
    command.add("-Dcatalina.home=" + home);
    command.add("-Dcatalina.base=" + base);
    command.add("-Djava.util.logging.manager=org.apache.juli.ClassLoaderLogManager");
    command.add("-Djava.util.logging.config.file=" + conf.resolve("logging.properties"));
    command.add("-classpath");
    command.add(
        home.resolve("bin").resolve("bootstrap.jar")
            + File.pathSeparator
            + home.resolve("bin").resolve("tomcat-juli.jar"));
    command.add("org.apache.catalina.startup.Bootstrap");
    command.add("start");
    return command;
  }

  /** server.xml: one HTTP connector on 127.0.0.1:{@code port}, shutdown port disabled. */
  static String serverXml(int port) {
    return """
        <?xml version="1.0" encoding="UTF-8"?>
        <!-- SPDX-License-Identifier: Apache-2.0 -->
        <!-- Generated by the Argos sample-app smoke runner (one run, 127.0.0.1 only). -->
        <Server port="-1" shutdown="SHUTDOWN">
          <Listener className="org.apache.catalina.startup.VersionLoggerListener" />
          <Listener className="org.apache.catalina.core.JreMemoryLeakPreventionListener" />
          <Listener className="org.apache.catalina.core.ThreadLocalLeakPreventionListener" />
          <Service name="Catalina">
            <Connector port="%d" address="127.0.0.1" protocol="HTTP/1.1" connectionTimeout="20000" />
            <Engine name="Catalina" defaultHost="localhost">
              <Host name="localhost" appBase="webapps" unpackWARs="true" autoDeploy="false" />
            </Engine>
          </Service>
        </Server>
        """
        .formatted(port);
  }
}
