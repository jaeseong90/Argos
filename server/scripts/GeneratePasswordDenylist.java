import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.Duration;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;
import java.util.TreeSet;

/**
 * Regenerates server/src/main/resources/security/password-denylist.sha256, the banned password list
 * of the password policy (docs/16 section 7.9, section 15 #10, SEC-48).
 *
 * <p>A developer tool, run by hand from the repository root when the source list is bumped; nothing
 * in the build or at run time downloads anything:
 *
 * <pre>
 *   java server/scripts/GeneratePasswordDenylist.java
 * </pre>
 *
 * It downloads SecLists Passwords/Common-Credentials/10k-most-common.txt (MIT License, attribution
 * in NOTICE) at a pinned commit, checks the SHA-256 of the download, lower-cases every entry with
 * the same rule as io.argos.server.auth.password.PasswordDenylist (Locale.ROOT, UTF-8) and writes
 * the sorted, unique SHA-256 hex values, so the resource holds no password in plain text and the
 * output is reproducible byte for byte. To bump the list, change COMMIT and SOURCE_SHA256 together
 * and update the entry count in PasswordDenylist and the commit in NOTICE.
 */
public final class GeneratePasswordDenylist {

  private static final String COMMIT = "913b327317496d062bcc7cace524aaad8a693be2";
  private static final String SOURCE_PATH = "Passwords/Common-Credentials/10k-most-common.txt";
  private static final String SOURCE_SHA256 =
      "68782d6a4a19a4768d5f15dd66bd534e7a33055cc755411e33f16d18c50fdcce";
  private static final Path OUTPUT =
      Path.of("server/src/main/resources/security/password-denylist.sha256");

  private GeneratePasswordDenylist() {}

  public static void main(String[] args) throws Exception {
    String url =
        "https://raw.githubusercontent.com/danielmiessler/SecLists/" + COMMIT + "/" + SOURCE_PATH;
    byte[] source = download(url);
    String actual = hex(sha256(source));
    if (!SOURCE_SHA256.equals(actual)) {
      throw new IllegalStateException("Unexpected SHA-256 of the source list: " + actual);
    }
    TreeSet<String> hashes = new TreeSet<>();
    for (String line : new String(source, StandardCharsets.UTF_8).split("\n", -1)) {
      String entry = line.endsWith("\r") ? line.substring(0, line.length() - 1) : line;
      if (!entry.isEmpty()) {
        hashes.add(hex(sha256(entry.toLowerCase(Locale.ROOT).getBytes(StandardCharsets.UTF_8))));
      }
    }
    List<String> lines = new ArrayList<>();
    lines.add("# The banned passwords of the password policy (docs/16 section 7.9, SEC-48).");
    lines.add("# SHA-256 hex of each lower-cased entry of SecLists " + SOURCE_PATH);
    lines.add("# at commit " + COMMIT + " (MIT License, see NOTICE).");
    lines.add("# Generated by server/scripts/GeneratePasswordDenylist.java: do not edit.");
    lines.addAll(hashes);
    Files.createDirectories(OUTPUT.getParent());
    Files.writeString(OUTPUT, String.join("\n", lines) + "\n", StandardCharsets.US_ASCII);
    System.out.println(hashes.size() + " entries written to " + OUTPUT);
  }

  private static byte[] download(String url) throws IOException, InterruptedException {
    HttpClient http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(20)).build();
    HttpRequest request =
        HttpRequest.newBuilder(URI.create(url)).timeout(Duration.ofSeconds(60)).build();
    HttpResponse<byte[]> response = http.send(request, HttpResponse.BodyHandlers.ofByteArray());
    if (response.statusCode() != 200) {
      throw new IOException("GET " + url + ": HTTP " + response.statusCode());
    }
    return response.body();
  }

  private static byte[] sha256(byte[] bytes) throws NoSuchAlgorithmException {
    return MessageDigest.getInstance("SHA-256").digest(bytes);
  }

  private static String hex(byte[] bytes) {
    return HexFormat.of().formatHex(bytes);
  }
}
