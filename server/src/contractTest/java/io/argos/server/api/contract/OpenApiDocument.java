package io.argos.server.api.contract;

import io.argos.server.api.openapi.ContractServer;
import io.argos.server.testing.auth.ApiResponse;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import org.yaml.snakeyaml.DumperOptions;
import org.yaml.snakeyaml.LoaderOptions;
import org.yaml.snakeyaml.Yaml;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * The committed OpenAPI document {@code docs/api/openapi.yaml} (ADR-0003 C-28, ADR-0010 C-151, 19
 * §3.2, 14 §8) and how it is generated:
 *
 * <ol>
 *   <li>the web layer of the server starts without databases ({@link ContractServer}: every
 *       controller, filter and springdoc; collaborators are stubs, which the document does not
 *       see);
 *   <li>springdoc's document is read as a viewer from {@code /api/v1/openapi};
 *   <li>{@code info.version} is set to {@value #API_VERSION}: the committed file describes the API
 *       version of the path, not a build, so it does not change with every release (the running
 *       server still reports its build version);
 *   <li>it is written as YAML with a fixed key order: {@code openapi}, {@code info}, {@code
 *       servers}, {@code paths}, {@code components} first, every other mapping sorted by key; LF
 *       line ends, no line folding, a final line feed. Lists keep their order (parameters, enums,
 *       {@code required}). The file starts with the comment lines of {@link #HEADER} (SPDX).
 * </ol>
 *
 * {@code ./gradlew :server:generateOpenApi} writes the file ({@link GenerateOpenApi}); {@code
 * OpenApiContractTest} fails when the committed file differs from a fresh generation.
 */
public final class OpenApiDocument {

  /** The committed file, relative to the repository root. */
  public static final String COMMITTED = "docs/api/openapi.yaml";

  /** {@code info.version} of the committed file. */
  public static final String API_VERSION = "v1";

  private static final List<String> TOP_LEVEL =
      List.of("openapi", "info", "jsonSchemaDialect", "servers", "security", "tags", "paths");

  private static final JsonMapper JSON = JsonMapper.builder().build();

  private OpenApiDocument() {}

  /** The repository root ({@code argos.repositoryRoot}, set by the build). */
  public static Path repositoryRoot() {
    return Path.of(System.getProperty("argos.repositoryRoot", ".."));
  }

  /** The committed file. */
  public static Path committedFile() {
    return repositoryRoot().resolve(COMMITTED);
  }

  /** Starts the web layer, reads its document and renders the committed form. */
  public static String generate() {
    try (ContractServer server = ContractServer.start()) {
      return generate(server);
    }
  }

  /** The committed form of the document of a running web layer. */
  public static String generate(ContractServer server) {
    ApiResponse response = server.client("viewer").get("/api/v1/openapi");
    if (response.status() != 200) {
      throw new IllegalStateException("No OpenAPI document: HTTP " + response.status());
    }
    return render(JSON.readTree(response.body()));
  }

  /** The committed YAML of a document. */
  public static String render(JsonNode document) {
    Object tree = normalize(toPlain(document), true);
    DumperOptions options = new DumperOptions();
    options.setDefaultFlowStyle(DumperOptions.FlowStyle.BLOCK);
    options.setIndent(2);
    options.setIndicatorIndent(0);
    options.setSplitLines(false);
    options.setWidth(Integer.MAX_VALUE);
    options.setLineBreak(DumperOptions.LineBreak.UNIX);
    options.setAllowUnicode(true);
    String yaml = new Yaml(options).dump(tree);
    return HEADER + (yaml.endsWith("\n") ? yaml : yaml + "\n");
  }

  /**
   * The comment lines at the top of the committed file: the SPDX header that every file of the
   * repository carries (T-BLD-007, test/lint/check-spdx.sh) and how the file is made.
   */
  static final String HEADER =
      "# SPDX-License-Identifier: Apache-2.0\n"
          + "#\n"
          + "# Argos REST API v1. Generated by ./gradlew :server:generateOpenApi from the server's"
          + " controllers\n"
          + "# (ADR-0003 C-28); do not edit by hand: the contract test fails when this file differs"
          + " from a\n"
          + "# fresh generation.\n";

  /** Reads a YAML (or JSON) document into a tree. */
  public static JsonNode readYaml(String text) {
    LoaderOptions loader = new LoaderOptions();
    loader.setCodePointLimit(64 * 1024 * 1024);
    loader.setMaxAliasesForCollections(10);
    Object plain = new Yaml(loader).load(text);
    return JSON.valueToTree(plain);
  }

  /** Reads the committed file; null when it does not exist. */
  public static String readCommitted() {
    Path file = committedFile();
    if (!Files.exists(file)) {
      return null;
    }
    try {
      return Files.readString(file, StandardCharsets.UTF_8).replace("\r\n", "\n");
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }

  private static Object toPlain(JsonNode node) {
    if (node.isObject()) {
      Map<String, Object> map = new LinkedHashMap<>();
      for (Map.Entry<String, JsonNode> e : node.properties()) {
        map.put(e.getKey(), toPlain(e.getValue()));
      }
      return map;
    }
    if (node.isArray()) {
      List<Object> list = new ArrayList<>();
      node.forEach(e -> list.add(toPlain(e)));
      return list;
    }
    if (node.isNull()) {
      return null;
    }
    if (node.isBoolean()) {
      return node.booleanValue();
    }
    if (node.isIntegralNumber()) {
      return node.canConvertToLong() ? (Object) node.longValue() : node.bigIntegerValue();
    }
    if (node.isNumber()) {
      return node.doubleValue();
    }
    return node.asString();
  }

  /** Sorted mappings (the top level in {@link #TOP_LEVEL} order), {@code info.version} fixed. */
  @SuppressWarnings("unchecked")
  private static Object normalize(Object value, boolean top) {
    if (value instanceof Map<?, ?> map) {
      Map<String, Object> sorted = new TreeMap<>();
      map.forEach((k, v) -> sorted.put(String.valueOf(k), normalize(v, false)));
      if (!top) {
        return new LinkedHashMap<>(sorted);
      }
      if (sorted.get("info") instanceof Map<?, ?> info) {
        ((Map<String, Object>) info).put("version", API_VERSION);
      }
      Map<String, Object> ordered = new LinkedHashMap<>();
      for (String key : TOP_LEVEL) {
        if (sorted.containsKey(key)) {
          ordered.put(key, sorted.remove(key));
        }
      }
      ordered.putAll(sorted);
      return ordered;
    }
    if (value instanceof List<?> list) {
      List<Object> out = new ArrayList<>(list.size());
      list.forEach(e -> out.add(normalize(e, false)));
      return out;
    }
    return value;
  }
}
