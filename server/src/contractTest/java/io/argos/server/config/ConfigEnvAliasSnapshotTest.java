package io.argos.server.config;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.boot.env.YamlPropertySourceLoader;
import org.springframework.core.env.ConfigurableEnvironment;
import org.springframework.core.env.MutablePropertySources;
import org.springframework.core.env.PropertySource;
import org.springframework.core.env.StandardEnvironment;
import org.springframework.core.env.SystemEnvironmentPropertySource;
import org.springframework.core.io.ClassPathResource;

/**
 * T-API-009 (server part, names outside {@code argos.*}): the short environment names of 17 §3.8
 * and the Spring keys operators rely on are a public contract like the {@code argos.*} keys (17
 * §6.1, ADR-0010 C-96). {@code config-env-aliases.txt} fixes them; this test fails when a short
 * name disappears, is renamed, sets another key or is added, and when a listed Spring key changes
 * its packaged default, without the file being changed by hand in the same change. The file is
 * never regenerated by a test.
 */
@Tag("req:O-R03")
class ConfigEnvAliasSnapshotTest {

  static final String SNAPSHOT = "config-env-aliases.txt";
  static final String SNAPSHOT_PATH = "server/src/contractTest/resources/" + SNAPSHOT;

  static final String ALIASES = "aliases";
  static final String SPRING_KEYS = "spring-keys";

  /** An unset key in the {@code spring-keys} section. */
  static final String NONE = "(none)";

  /** The sections of the snapshot: section name to (first column to second column), in order. */
  private static Map<String, Map<String, String>> snapshot() throws IOException {
    Map<String, Map<String, String>> sections = new LinkedHashMap<>();
    try (InputStream in =
        ConfigEnvAliasSnapshotTest.class.getClassLoader().getResourceAsStream(SNAPSHOT)) {
      assertThat(in).as(SNAPSHOT_PATH + " on the contractTest class path").isNotNull();
      Map<String, String> current = null;
      for (String line : new String(in.readAllBytes(), StandardCharsets.UTF_8).split("\n", -1)) {
        String l = line.stripTrailing();
        if (l.isEmpty() || l.startsWith("#")) {
          continue;
        }
        if (l.startsWith("[") && l.endsWith("]")) {
          current = new LinkedHashMap<>();
          assertThat(sections.put(l.substring(1, l.length() - 1), current))
              .as("section %s appears once", l)
              .isNull();
          continue;
        }
        String[] columns = l.split("\t", -1);
        assertThat(current).as("line before the first section: %s", l).isNotNull();
        assertThat(columns).as("two tab-separated columns: %s", l).hasSize(2);
        assertThat(current.put(columns[0], columns[1])).as("duplicate %s", columns[0]).isNull();
      }
    }
    assertThat(sections.keySet()).containsExactly(ALIASES, SPRING_KEYS);
    return sections;
  }

  /**
   * The packaged {@code application.yml} as the server sees it with no environment variable set:
   * loaded under Spring Boot's source name and reduced by {@link PackagedSettingsPostProcessor}.
   */
  private static ConfigurableEnvironment packagedEnvironment() throws IOException {
    StandardEnvironment environment = new StandardEnvironment();
    MutablePropertySources sources = environment.getPropertySources();
    sources.remove(StandardEnvironment.SYSTEM_PROPERTIES_PROPERTY_SOURCE_NAME);
    sources.replace(
        StandardEnvironment.SYSTEM_ENVIRONMENT_PROPERTY_SOURCE_NAME,
        new SystemEnvironmentPropertySource(
            StandardEnvironment.SYSTEM_ENVIRONMENT_PROPERTY_SOURCE_NAME, Map.of()));
    List<PropertySource<?>> yaml =
        new YamlPropertySourceLoader()
            .load(
                "Config resource 'class path resource [application.yml]' via location"
                    + " 'optional:classpath:/'",
                new ClassPathResource("application.yml"));
    yaml.forEach(sources::addLast);
    PackagedSettingsPostProcessor.apply(environment);
    return environment;
  }

  @Test
  @DisplayName("T-API-009 short environment names and their keys match config-env-aliases.txt")
  void aliasesMatchSnapshot() throws IOException {
    List<String> diff =
        diff(snapshot().get(ALIASES), new TreeMap<>(EnvironmentAliases.ALIASES), "sets");
    assertThat(diff)
        .as(
            "Short environment names are a public contract (T-API-009, 17 §3.8, §6.1, ADR-0010"
                + " C-96). EnvironmentAliases.ALIASES and the application.yml placeholders differ"
                + " from %s:%n%s%n%nA removed or renamed name, or one that sets another key, breaks"
                + " operators' Compose files and environments: keep the old name or document the"
                + " change (CHANGELOG, report). If the change is intended, and for every new name,"
                + " update the [aliases] section of %s in the same change, by hand.",
            SNAPSHOT_PATH, String.join("\n", diff), SNAPSHOT_PATH)
        .isEmpty();
  }

  @Test
  @DisplayName("T-API-009 Spring keys of the contract keep their packaged defaults")
  void springKeysMatchSnapshot() throws IOException {
    Map<String, String> expected = snapshot().get(SPRING_KEYS);
    ConfigurableEnvironment environment = packagedEnvironment();
    Map<String, String> actual = new TreeMap<>();
    for (String key : expected.keySet()) {
      String value = environment.getProperty(key);
      actual.put(key, value == null ? NONE : value);
    }
    List<String> diff = diff(expected, actual, "defaults to");
    assertThat(diff)
        .as(
            "The packaged defaults of these Spring keys are a public contract (T-API-009,"
                + " ADR-0010 C-96; 02 C-7 for the management port):%n%s%n%nIf the change is"
                + " intended, update the [spring-keys] section of %s in the same change, by hand,"
                + " and report it.",
            String.join("\n", diff), SNAPSHOT_PATH)
        .isEmpty();
  }

  @Test
  @DisplayName("T-API-009 the alias snapshot has two sorted sections of well-formed names")
  void snapshotWellFormed() throws IOException {
    Map<String, Map<String, String>> sections = snapshot();
    assertThat(List.copyOf(sections.get(ALIASES).keySet()))
        .isSorted()
        .allMatch(name -> name.matches("ARGOS_[A-Z0-9_]+"));
    assertThat(List.copyOf(sections.get(SPRING_KEYS).keySet()))
        .isSorted()
        .noneMatch(key -> key.startsWith("argos."));
  }

  @Test
  @DisplayName("T-API-009 a removed, renamed, retargeted or new alias is reported")
  void diffReportsEveryChange() {
    Map<String, String> expected = new LinkedHashMap<>();
    expected.put("ARGOS_A", "argos.a");
    expected.put("ARGOS_B", "argos.b");
    expected.put("ARGOS_C", "argos.c");
    Map<String, String> actual = new LinkedHashMap<>();
    actual.put("ARGOS_A", "argos.a");
    actual.put("ARGOS_B", "argos.other");
    actual.put("ARGOS_D", "argos.c");
    assertThat(diff(expected, actual, "sets"))
        .containsExactly(
            "- ARGOS_B sets argos.b",
            "+ ARGOS_B sets argos.other    (changed)",
            "- ARGOS_C sets argos.c    (removed or renamed)",
            "+ ARGOS_D sets argos.c    (new)");
    assertThat(diff(expected, expected, "sets")).isEmpty();
  }

  /** Readable differences between two name-to-value maps. */
  static List<String> diff(Map<String, String> expected, Map<String, String> actual, String verb) {
    List<String> diff = new ArrayList<>();
    expected.forEach(
        (name, value) -> {
          String now = actual.get(name);
          if (now == null) {
            diff.add("- " + name + " " + verb + " " + value + "    (removed or renamed)");
          } else if (!now.equals(value)) {
            diff.add("- " + name + " " + verb + " " + value);
            diff.add("+ " + name + " " + verb + " " + now + "    (changed)");
          }
        });
    actual.forEach(
        (name, value) -> {
          if (!expected.containsKey(name)) {
            diff.add("+ " + name + " " + verb + " " + value + "    (new)");
          }
        });
    return diff;
  }
}
