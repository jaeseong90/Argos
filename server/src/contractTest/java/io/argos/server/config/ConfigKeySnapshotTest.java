package io.argos.server.config;

import static org.assertj.core.api.Assertions.assertThat;

import io.argos.server.config.ConfigKeyCatalog.ConfigKey;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * T-API-009 (server part): the {@code argos.*} keys are a public contract (O-R03, ADR-0010 C-96).
 * {@code config-keys.txt} lists every key of {@link ArgosProperties} with its type and default;
 * this test fails when a key disappears, is renamed, changes its type or default, or is added
 * without updating the file. The file is changed by hand, in the same change as the key, never
 * regenerated by a test.
 */
@Tag("req:O-R03")
class ConfigKeySnapshotTest {

  static final String SNAPSHOT = "config-keys.txt";
  static final String SNAPSHOT_PATH = "server/src/contractTest/resources/" + SNAPSHOT;

  /** The key lines of the snapshot, in file order (comments and blank lines skipped). */
  private static List<String> snapshotLines() throws IOException {
    List<String> lines = new ArrayList<>();
    try (InputStream in =
        ConfigKeySnapshotTest.class.getClassLoader().getResourceAsStream(SNAPSHOT)) {
      assertThat(in).as(SNAPSHOT_PATH + " on the contractTest class path").isNotNull();
      for (String line : new String(in.readAllBytes(), StandardCharsets.UTF_8).split("\n", -1)) {
        String l = line.stripTrailing();
        if (!l.isEmpty() && !l.startsWith("#")) {
          lines.add(l);
        }
      }
    }
    return lines;
  }

  private static String keyOf(String line) {
    int tab = line.indexOf('\t');
    return tab < 0 ? line : line.substring(0, tab);
  }

  private static Map<String, String> snapshot() throws IOException {
    Map<String, String> lines = new LinkedHashMap<>();
    for (String line : snapshotLines()) {
      lines.put(keyOf(line), line);
    }
    return lines;
  }

  private static Map<String, String> current() {
    Map<String, String> lines = new LinkedHashMap<>();
    for (ConfigKey key : ConfigKeyCatalog.keys()) {
      lines.put(key.name(), key.snapshotLine());
    }
    return lines;
  }

  @Test
  @DisplayName("T-API-009 server config keys: names, types and defaults match config-keys.txt")
  void keysMatchSnapshot() throws IOException {
    Map<String, String> actual = current();
    List<String> diff = diff(snapshot(), actual);
    assertThat(diff)
        .as(
            "Configuration keys are a public contract (T-API-009, O-R03). The argos.* keys of"
                + " ArgosProperties differ from %s:%n%s%n%nA removed, renamed or retyped key or a"
                + " changed default breaks operators' configuration files: keep the old key or"
                + " document the change (CHANGELOG, report). If the change is intended, and for"
                + " every new key, update %s in the same change, by hand (tab-separated: key, type,"
                + " default). The complete current list:%n%s",
            SNAPSHOT_PATH,
            String.join("\n", diff),
            SNAPSHOT_PATH,
            String.join("\n", actual.values()))
        .isEmpty();
  }

  /** Readable differences between the snapshot lines and the current lines, keyed by key. */
  static List<String> diff(Map<String, String> expected, Map<String, String> actual) {
    List<String> diff = new ArrayList<>();
    expected.forEach(
        (key, line) -> {
          String now = actual.get(key);
          if (now == null) {
            diff.add("- " + line.replace('\t', ' ') + "    (removed or renamed)");
          } else if (!now.equals(line)) {
            diff.add("- " + line.replace('\t', ' '));
            diff.add("+ " + now.replace('\t', ' ') + "    (type or default changed)");
          }
        });
    actual.forEach(
        (key, line) -> {
          if (!expected.containsKey(key)) {
            diff.add("+ " + line.replace('\t', ' ') + "    (new key)");
          }
        });
    return diff;
  }

  @Test
  @DisplayName(
      "T-API-009 a removed, renamed, retyped or re-defaulted key and a new key are reported")
  void diffReportsEveryChange() {
    Map<String, String> expected = new LinkedHashMap<>();
    expected.put("argos.a", "argos.a\tint\t1");
    expected.put("argos.b", "argos.b\tint\t2");
    expected.put("argos.c", "argos.c\tstring\tx");
    expected.put("argos.d", "argos.d\tint\t4");
    Map<String, String> actual = new LinkedHashMap<>();
    actual.put("argos.a", "argos.a\tint\t1");
    actual.put("argos.b", "argos.b\tint\t3");
    actual.put("argos.c", "argos.c\tlong\tx");
    actual.put("argos.e", "argos.e\tint\t4");
    assertThat(diff(expected, actual))
        .containsExactly(
            "- argos.b int 2",
            "+ argos.b int 3    (type or default changed)",
            "- argos.c string x",
            "+ argos.c long x    (type or default changed)",
            "- argos.d int 4    (removed or renamed)",
            "+ argos.e int 4    (new key)");
    assertThat(diff(expected, expected)).isEmpty();
  }

  @Test
  @DisplayName("T-API-009 the snapshot is sorted and has no duplicate keys")
  void snapshotWellFormed() throws IOException {
    List<String> keys = snapshotLines().stream().map(ConfigKeySnapshotTest::keyOf).toList();
    assertThat(keys).isSorted().doesNotHaveDuplicates().allMatch(k -> k.startsWith("argos."));
    assertThat(snapshotLines())
        .allMatch(l -> l.split("\t", -1).length == 3, "key<TAB>type<TAB>default");
  }
}
