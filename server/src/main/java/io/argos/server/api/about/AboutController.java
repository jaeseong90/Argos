package io.argos.server.api.about;

import io.argos.proto.ProtocolVersion;
import io.argos.server.api.Envelope;
import io.argos.server.api.openapi.ArgosLimits;
import io.argos.server.api.openapi.ArgosSource;
import io.argos.server.auth.RequiresRole;
import io.argos.server.auth.Role;
import io.argos.server.config.ServerBuild;
import io.argos.server.storage.postgres.catalog.CatalogRepository;
import io.swagger.v3.oas.annotations.Operation;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Version and open-source information of the installation (14 §4.14 {@code GET /about}, {@code GET
 * /about/licenses}; O-R12, O-L04; ADR-0010 C-153; WO-39), for every signed-in user. Nothing is
 * fetched from outside: the version comes from the build information ({@link ServerBuild}), the
 * agent versions from the stored instances, the component lists from the build's resources ({@link
 * LicenseCatalog}, generated by WO-44).
 */
@RestController
@RequiresRole(Role.VIEWER)
public class AboutController {

  /** Distinct agent versions listed at most. */
  static final int MAX_AGENT_VERSIONS = 1_000;

  /**
   * The document that states the supported versions: a path in the source distribution, linked by
   * the UI as text (no outbound call).
   */
  static final String SUPPORT_POLICY = "SECURITY.md#supported-versions";

  private final ServerBuild build;
  private final CatalogRepository catalog;
  private final LicenseCatalog licenses;
  private final long startedNanos = System.nanoTime();

  public AboutController(ServerBuild build, CatalogRepository catalog) {
    this.build = build;
    this.catalog = catalog;
    this.licenses = new LicenseCatalog(AboutController.class.getClassLoader());
  }

  /** The version information (14 §4.14). */
  @GetMapping("/api/v1/about")
  @Operation(
      operationId = "about_get",
      summary = "Server version, protocol version, agent versions in use and uptime",
      description =
          "version and commit of the server build (the UI has the server's version), the agent"
              + " protocol version, the agent versions of the instances that are not archived"
              + " with their counts (most common first, at most 1,000; a null version is an agent"
              + " that reported none), whole seconds since the server started and the repository"
              + " document of the support policy.")
  @ArgosLimits(rowsMax = MAX_AGENT_VERSIONS, timeoutS = CatalogRepository.STATEMENT_TIMEOUT_S)
  @ArgosSource({"postgres:instances", "postgres:apps", "memory:build_info"})
  public Envelope<AboutViews.About> about() {
    List<AboutViews.AgentVersion> versions =
        catalog.agentVersionCounts(MAX_AGENT_VERSIONS).stream()
            .map(v -> new AboutViews.AgentVersion(v.version(), v.count()))
            .toList();
    return Envelope.of(
        new AboutViews.About(
            build.version(),
            build.commit(),
            ProtocolVersion.CURRENT,
            versions,
            TimeUnit.NANOSECONDS.toSeconds(System.nanoTime() - startedNanos),
            SUPPORT_POLICY));
  }

  /** The open-source components of the server, the UI and the agent (14 §4.14). */
  @GetMapping("/api/v1/about/licenses")
  @Operation(
      operationId = "about_licenses_get",
      summary = "Open-source components of the server, the UI and the agent",
      description =
          "Per part (server, ui, agent) the components of this build with their version and"
              + " license, by name. A build without the generated list answers available=false,"
              + " reason=not_generated (reason=unreadable for a list of the wrong form); at most"
              + " 5,000 components per part (truncated). Read from the build, no network.")
  @ArgosSource({"memory:build_resources"})
  public Envelope<AboutViews.Licenses> licenses() {
    return Envelope.of(licenses.licenses());
  }
}
