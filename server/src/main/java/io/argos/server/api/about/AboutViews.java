package io.argos.server.api.about;

import com.fasterxml.jackson.annotation.JsonProperty;
import io.argos.server.api.openapi.ArgosUntrusted;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.media.Schema.RequiredMode;
import java.util.List;
import org.jspecify.annotations.Nullable;

/** The response types of {@code GET /about} and {@code GET /about/licenses} (14 §4.14, WO-39). */
public final class AboutViews {

  private AboutViews() {}

  /**
   * The version information of the installation (O-R12, 15 §9.10 {@code /admin/about}).
   *
   * @param version the server version (the UI is served by the server and has the same version)
   * @param commit the commit the server was built from, {@code unknown} without build information
   * @param protocolVersion the agent protocol version this server speaks (11)
   * @param agentVersions the agent versions of the instances that are not archived with their
   *     counts, the most common first
   * @param uptimeS whole seconds since the server started
   * @param supportPolicyUrl the repository document that states the supported versions, a relative
   *     path (no outbound call, the UI links it as a document of the source distribution)
   */
  @Schema(name = "About")
  public record About(
      // Not collected, but every "version" property is rendered as text only (14 §2.10 lint).
      @ArgosUntrusted @Schema(requiredMode = RequiredMode.REQUIRED) String version,
      @Schema(requiredMode = RequiredMode.REQUIRED) String commit,
      @JsonProperty("protocol_version") @Schema(requiredMode = RequiredMode.REQUIRED)
          int protocolVersion,
      @JsonProperty("agent_versions") @Schema(requiredMode = RequiredMode.REQUIRED)
          List<AgentVersion> agentVersions,
      @JsonProperty("uptime_s") @Schema(requiredMode = RequiredMode.REQUIRED) long uptimeS,
      @JsonProperty("support_policy_url") @Nullable String supportPolicyUrl) {

    public About {
      agentVersions = List.copyOf(agentVersions);
    }
  }

  /**
   * An agent version in use.
   *
   * @param version the version the agent reported, null when it reported none
   * @param count instances that are not archived running it
   */
  @Schema(name = "AboutAgentVersion")
  public record AgentVersion(
      @ArgosUntrusted @Nullable String version,
      @Schema(requiredMode = RequiredMode.REQUIRED) long count) {}

  /**
   * The open-source components of the server, the UI and the agent (O-L04, 15 §9.10 {@code
   * /admin/licenses}). The lists are generated by the build (WO-44); a build without them answers
   * {@code available=false, reason=not_generated}.
   *
   * @param server the server's components
   * @param ui the UI's components
   * @param agent the agent's components
   */
  @Schema(name = "AboutLicenses")
  public record Licenses(
      @Schema(requiredMode = RequiredMode.REQUIRED) Section server,
      @Schema(requiredMode = RequiredMode.REQUIRED) Section ui,
      @Schema(requiredMode = RequiredMode.REQUIRED) Section agent) {}

  /**
   * One part's component list.
   *
   * @param available whether this build carries the list
   * @param reason {@code not_generated} (the build has no list) or {@code unreadable} (the list is
   *     not valid JSON of the expected form) when not available; null when available
   * @param components the components by name, empty when not available
   * @param truncated whether the list was cut at {@value LicenseCatalog#MAX_COMPONENTS} components
   */
  @Schema(name = "AboutLicenseSection")
  public record Section(
      @Schema(requiredMode = RequiredMode.REQUIRED) boolean available,
      @Schema(allowableValues = {"not_generated", "unreadable"}) @Nullable String reason,
      @Schema(requiredMode = RequiredMode.REQUIRED) List<Component> components,
      @Schema(requiredMode = RequiredMode.REQUIRED) boolean truncated) {

    public Section {
      components = List.copyOf(components);
    }

    /** A part whose list this build does not carry. */
    static Section missing(String reason) {
      return new Section(false, reason, List.of(), false);
    }
  }

  /**
   * An open-source component.
   *
   * @param name its name (for example {@code group:artifact} or the npm package name)
   * @param version its version, null when the list gives none
   * @param license its license (SPDX expression), null when the list gives none
   */
  @Schema(name = "AboutLicenseComponent")
  public record Component(
      @ArgosUntrusted @Schema(requiredMode = RequiredMode.REQUIRED) String name,
      @ArgosUntrusted @Nullable String version,
      @ArgosUntrusted @Nullable String license) {}
}
