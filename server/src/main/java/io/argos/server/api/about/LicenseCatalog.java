package io.argos.server.api.about;

import java.io.IOException;
import java.io.InputStream;
import java.net.URL;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * The open-source component lists of this build (O-L04, ADR-0010 C-153): the class path resources
 * {@code META-INF/argos/licenses/server.json}, {@code ui.json} and {@code agent.json}, generated by
 * the build (WO-44). Each holds an array of {@code {name, version, license}} objects, or an object
 * with such an array as {@code components}. A missing resource is {@code not_generated}, one that
 * is not of that form (or larger than {@value #MAX_BYTES} bytes) {@code unreadable}; at most
 * {@value #MAX_COMPONENTS} components are listed, texts are cut at {@value #MAX_TEXT} characters.
 *
 * <p>The resources are read once (they cannot change while the server runs); nothing is fetched
 * from the network.
 */
final class LicenseCatalog {

  /** Where the lists are on the class path. */
  static final String DIRECTORY = "META-INF/argos/licenses/";

  /** Components listed per part at most. */
  static final int MAX_COMPONENTS = 5_000;

  /** Largest list file read. */
  static final int MAX_BYTES = 4 * 1024 * 1024;

  /** Longest name, version or license text kept. */
  static final int MAX_TEXT = 256;

  private static final Logger LOG = LoggerFactory.getLogger(LicenseCatalog.class);
  private static final JsonMapper JSON = JsonMapper.builder().build();

  private final ClassLoader loader;
  private volatile AboutViews.Licenses cached;

  LicenseCatalog(ClassLoader loader) {
    this.loader = loader;
  }

  /** The three lists (read on the first call). */
  AboutViews.Licenses licenses() {
    AboutViews.Licenses out = cached;
    if (out == null) {
      out = new AboutViews.Licenses(section("server"), section("ui"), section("agent"));
      cached = out;
    }
    return out;
  }

  /** One part's list from {@code META-INF/argos/licenses/<part>.json}. */
  AboutViews.Section section(String part) {
    URL url = loader.getResource(DIRECTORY + part + ".json");
    if (url == null) {
      return AboutViews.Section.missing("not_generated");
    }
    byte[] bytes;
    try (InputStream in = url.openStream()) {
      bytes = in.readNBytes(MAX_BYTES + 1);
    } catch (IOException e) {
      LOG.warn("The {} license list cannot be read: {}", part, e.getClass().getSimpleName());
      return AboutViews.Section.missing("unreadable");
    }
    if (bytes.length > MAX_BYTES) {
      LOG.warn("The {} license list is larger than {} bytes", part, MAX_BYTES);
      return AboutViews.Section.missing("unreadable");
    }
    try {
      return parse(JSON.readTree(bytes));
    } catch (JacksonException | IllegalArgumentException e) {
      LOG.warn("The {} license list is not a list of components", part);
      return AboutViews.Section.missing("unreadable");
    }
  }

  private static AboutViews.Section parse(JsonNode root) {
    JsonNode list = root != null && root.isObject() ? root.path("components") : root;
    if (list == null || !list.isArray()) {
      throw new IllegalArgumentException("not an array");
    }
    List<AboutViews.Component> out = new ArrayList<>();
    boolean truncated = false;
    for (JsonNode n : list) {
      if (!n.isObject() || !n.path("name").isString() || n.path("name").asString().isBlank()) {
        throw new IllegalArgumentException("component without a name");
      }
      if (out.size() == MAX_COMPONENTS) {
        truncated = true;
        break;
      }
      out.add(
          new AboutViews.Component(
              text(n.path("name")),
              optionalText(n.path("version")),
              optionalText(n.path("license"))));
    }
    out.sort(
        Comparator.comparing(AboutViews.Component::name)
            .thenComparing(c -> c.version() == null ? "" : c.version()));
    return new AboutViews.Section(true, null, out, truncated);
  }

  private static String optionalText(JsonNode n) {
    return n.isString() && !n.asString().isBlank() ? text(n) : null;
  }

  private static String text(JsonNode n) {
    String s = n.asString().strip();
    return s.length() > MAX_TEXT ? s.substring(0, MAX_TEXT) : s;
  }
}
