package io.argos.server.session;

import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.UUID;

/**
 * The PostgreSQL writes of the instance state (12 §4.2, ADR-0010 C-128: WO-22 owns the state
 * columns of {@code instances}) and of the {@code events} rows of transitions, {@code AgentBye} and
 * the server's start and stop (the input contract of {@code api.events.Outages}). Implemented in
 * {@code io.argos.server.storage.postgres.instance} (SRV-01: JDBC only in storage); called only
 * from the state writer thread ({@link InstanceStateWriter}), never from a session stream or a data
 * call, so that a PostgreSQL outage never blocks the collector (12 §3.9).
 *
 * <p>Every method may throw a Spring {@code DataAccessException}.
 */
public interface InstanceStateStore {

  /** Writes the state columns of each row ({@code status}, {@code warn_flags}, ...). */
  void writeStates(List<StateRow> rows);

  /**
   * Archives instances that will not come back under their id (a temporary {@code host:pid}
   * instance merged into the existing instance of its new name, 12 §4.3, ADR-0010 C-158 (2)):
   * {@code status = 'DOWN'}, no WARN flags, {@code archived_at} = the given time. Applied after the
   * state rows of the same flush, so an earlier state row never un-archives them.
   */
  void archiveInstances(Map<Integer, Instant> archivedAt);

  /** Inserts the events (ids are generated by the caller, so a retry after a timeout is safe). */
  void writeEvents(List<EventRow> events);

  /**
   * The instances that are not archived and whose stored status is not {@code DOWN}: the ones the
   * server left up, stale or warning when it stopped.
   */
  List<OpenInstance> openInstances();

  /** Instances that are not archived (the {@code argos_instances} gauge counts DOWN from it). */
  int countActiveInstances();

  /**
   * The state columns of one instance.
   *
   * @param instanceId {@code instances.id}
   * @param status {@code UP}, {@code STALE}, {@code DOWN} or {@code WARN}
   * @param warnFlags the WARN conditions (empty unless {@code WARN})
   * @param clockOffsetMs the clock offset (server − agent), null keeps the stored value
   * @param lastSeenAt the last heartbeat, null keeps the stored value
   */
  record StateRow(
      int instanceId,
      String status,
      List<String> warnFlags,
      Integer clockOffsetMs,
      Instant lastSeenAt) {

    /** Validates and copies. */
    public StateRow {
      Objects.requireNonNull(status, "status");
      warnFlags = warnFlags == null ? List.of() : List.copyOf(warnFlags);
    }
  }

  /**
   * One {@code events} row.
   *
   * @param id the row id
   * @param appId the application, null for a server event
   * @param env the environment, null for a server event
   * @param instanceId the instance, null for a server or application event
   * @param type {@code state}, {@code start} or {@code stop}
   * @param title English title (no collected data)
   * @param detailJson the {@code detail} JSON, or null
   * @param ts event time
   */
  record EventRow(
      UUID id,
      Integer appId,
      String env,
      Integer instanceId,
      String type,
      String title,
      String detailJson,
      Instant ts) {

    /** Validates. */
    public EventRow {
      Objects.requireNonNull(id, "id");
      Objects.requireNonNull(type, "type");
      Objects.requireNonNull(ts, "ts");
    }
  }

  /**
   * An instance the server found not {@code DOWN} at its start.
   *
   * @param instanceId {@code instances.id}
   * @param appId {@code apps.id}
   * @param env the application's environment
   * @param status the stored status
   * @param warnFlags the stored WARN conditions
   * @param clockOffsetMs the stored clock offset, or null
   */
  record OpenInstance(
      int instanceId,
      int appId,
      String env,
      String status,
      List<String> warnFlags,
      Integer clockOffsetMs) {

    /** Copies. */
    public OpenInstance {
      warnFlags = warnFlags == null ? List.of() : List.copyOf(warnFlags);
    }
  }
}
