package io.argos.server.admin.bootstrap;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.catchThrowableOfType;
import static org.mockito.Mockito.mock;

import io.argos.server.admin.token.TokenService;
import io.argos.server.admin.token.TokenService.Registration;
import io.argos.server.api.error.ApiException;
import io.argos.server.api.error.ErrorBody;
import io.argos.server.api.error.ErrorCode;
import io.argos.server.audit.Actor;
import io.argos.server.audit.AuditEvent;
import io.argos.server.audit.AuditResult;
import io.argos.server.audit.AuditService;
import io.argos.server.audit.Target;
import io.argos.server.collector.api.TokenHash;
import io.argos.server.collector.api.TokenLookup;
import io.argos.server.session.SessionRegistry;
import io.argos.server.storage.postgres.token.AgentTokenStore.StoredToken;
import io.argos.server.testing.auth.MutableClock;
import io.argos.server.testing.fakeagent.AgentTokens;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * {@link TokenService#register} (WO-41): a token generated by the installation is stored like an
 * issued one (hash and prefix only, the per-app limit, {@code TOKEN_ISSUED}), a second registration
 * of the same token changes nothing, and a malformed token is never echoed.
 */
@Tag("req:SEC-02")
@Tag("req:SEC-74")
@Tag("req:N-16")
class TokenRegisterTest {

  private static final int APP = 41;
  private static final int OTHER_APP = 42;
  private static final Pattern ANY_TOKEN = Pattern.compile("argos_[A-Za-z0-9_-]{40,}");

  record Recorded(AuditEvent event, Target target, AuditResult result, Map<String, ?> after) {}

  private final MutableClock clock = new MutableClock();
  private final MemoryTokenStore store = new MemoryTokenStore(Set.of(APP, OTHER_APP));
  private final List<Recorded> audits = new ArrayList<>();
  private final AuditService audit =
      (event, actor, target, result, before, after) ->
          audits.add(new Recorded(event, target, result, after == null ? Map.of() : after));
  private final TokenService service =
      new TokenService(store, audit, mock(TokenLookup.class), mock(SessionRegistry.class), clock);

  private static ErrorCode code(Runnable call, String reason) {
    ApiException e = catchThrowableOfType(ApiException.class, call::run);
    assertThat(e).isNotNull();
    assertThat(e.details()).extracting(ErrorBody.Detail::reason).contains(reason);
    return e.errorCode();
  }

  @Test
  @DisplayName(
      "T-NFR-16a register: SHA-256 and the 14-character prefix only, expiry 365 days, system"
          + " issuer, TOKEN_ISSUED (registered) without the token; again: ALREADY_ACTIVE, nothing"
          + " written")
  void registerIsHashOnlyAndIdempotent() {
    String token = AgentTokens.generate();
    assertThat(service.register(Actor.system(), APP, token, null))
        .isEqualTo(Registration.REGISTERED);
    assertThat(store.rows).hasSize(1);
    StoredToken row = store.rows.values().iterator().next();
    assertThat(row.hash()).isEqualTo(TokenHash.of(token));
    assertThat(row.hash().hex()).isEqualTo(AgentTokens.sha256Hex(token));
    assertThat(row.prefix()).isEqualTo(token.substring(0, 14));
    assertThat(row.issuedBy()).isNull();
    assertThat(row.expiresAt()).isEqualTo(clock.instant().plus(Duration.ofDays(365)));
    assertThat(String.valueOf(row)).doesNotContain(token);

    assertThat(audits).hasSize(1);
    Recorded issued = audits.get(0);
    assertThat(issued.event()).isEqualTo(AuditEvent.TOKEN_ISSUED);
    assertThat(issued.result()).isEqualTo(AuditResult.success("registered"));
    assertThat(issued.target()).isEqualTo(new Target("token", row.id().toString(), row.prefix()));
    assertThat(ANY_TOKEN.matcher(String.valueOf(issued)).find()).isFalse();

    clock.advance(Duration.ofMinutes(5));
    assertThat(service.register(Actor.system(), APP, token, null))
        .isEqualTo(Registration.ALREADY_ACTIVE);
    assertThat(store.rows).hasSize(1);
    assertThat(audits).hasSize(1);
  }

  @Test
  @DisplayName(
      "T-NFR-16a register: a revoked token stays revoked (ALREADY_INACTIVE), it is not re-added")
  void revokedStaysRevoked() {
    String token = AgentTokens.generate();
    service.register(Actor.system(), APP, token, null);
    store.revoke(store.rows.keySet().iterator().next(), clock.instant());
    assertThat(service.register(Actor.system(), APP, token, null))
        .isEqualTo(Registration.ALREADY_INACTIVE);
    assertThat(store.rows).hasSize(1);
  }

  @Test
  @DisplayName("T-NFR-16a register: a malformed token is refused (invalid_format) and never echoed")
  void malformed() {
    String good = AgentTokens.generate();
    for (String bad :
        List.of(
            good.substring(0, 48),
            good + "A",
            "token_" + good.substring(6),
            good.substring(0, 20) + "!" + good.substring(21),
            "")) {
      ApiException e =
          catchThrowableOfType(
              ApiException.class, () -> service.register(Actor.system(), APP, bad, null));
      assertThat(e.errorCode()).isEqualTo(ErrorCode.INVALID_REQUEST);
      assertThat(e.details()).extracting(ErrorBody.Detail::reason).contains("invalid_format");
      if (!bad.isEmpty()) {
        assertThat(String.valueOf(e.getMessage()) + e.clientMessage() + e.details())
            .doesNotContain(bad);
      }
    }
    assertThat(store.rows).isEmpty();
    assertThat(audits).isEmpty();
  }

  @Test
  @DisplayName(
      "T-NFR-16a register: the 5-active limit applies (token_limit, audited rejected); another"
          + " app's token is refused (registered_elsewhere); an unknown app is 404")
  void limitsAndConflicts() {
    for (int i = 0; i < TokenService.MAX_ACTIVE_PER_APP; i++) {
      service.issue(Actor.system(), APP, null);
    }
    audits.clear();
    assertThat(
            code(
                () -> service.register(Actor.system(), APP, AgentTokens.generate(), null),
                "token_limit"))
        .isEqualTo(ErrorCode.INVALID_STATE);
    assertThat(audits)
        .singleElement()
        .extracting(Recorded::result)
        .isEqualTo(AuditResult.rejected("token_limit"));

    String token = AgentTokens.generate();
    service.register(Actor.system(), OTHER_APP, token, null);
    // APP is full, so free a slot to reach the uniqueness check.
    store.revoke(
        store.rows.values().stream().filter(t -> t.appId() == APP).findFirst().get().id(),
        clock.instant());
    audits.clear();
    assertThat(
            code(() -> service.register(Actor.system(), APP, token, null), "registered_elsewhere"))
        .isEqualTo(ErrorCode.ALREADY_EXISTS);
    assertThat(audits)
        .singleElement()
        .extracting(Recorded::result)
        .isEqualTo(AuditResult.rejected("registered_elsewhere"));
    assertThat(ANY_TOKEN.matcher(String.valueOf(audits)).find()).isFalse();

    ApiException missing =
        catchThrowableOfType(
            ApiException.class,
            () -> service.register(Actor.system(), 999, AgentTokens.generate(), null));
    assertThat(missing.errorCode()).isEqualTo(ErrorCode.NOT_FOUND);
  }
}
