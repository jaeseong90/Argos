package io.argos.server.api.about;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.stream.Collectors;
import java.util.stream.IntStream;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * T-API-013a (unit part): {@code GET /about/licenses} reads the build's component lists {@code
 * META-INF/argos/licenses/<part>.json} (generated by WO-44) and answers {@code not_generated} for a
 * part without one, {@code unreadable} for one of the wrong form (ADR-0010 C-153, O-L04).
 */
@Tag("req:O-L04")
class LicenseCatalogTest {

  private static final JsonMapper JSON = JsonMapper.builder().build();

  @TempDir Path root;

  private LicenseCatalog catalog() throws IOException {
    Files.createDirectories(root.resolve(LicenseCatalog.DIRECTORY));
    return new LicenseCatalog(new URLClassLoader(new URL[] {root.toUri().toURL()}, null));
  }

  private void write(String part, String json) throws IOException {
    Path dir = Files.createDirectories(root.resolve(LicenseCatalog.DIRECTORY));
    Files.writeString(dir.resolve(part + ".json"), json, StandardCharsets.UTF_8);
  }

  @Test
  @DisplayName(
      "T-API-013a a build without the generated lists answers available=false,"
          + " reason=not_generated and no components for server, ui and agent")
  void notGenerated() throws IOException {
    AboutViews.Licenses l = catalog().licenses();
    for (AboutViews.Section s : new AboutViews.Section[] {l.server(), l.ui(), l.agent()}) {
      assertThat(s.available()).isFalse();
      assertThat(s.reason()).isEqualTo("not_generated");
      assertThat(s.components()).isEmpty();
      assertThat(s.truncated()).isFalse();
    }
    JsonNode json = JSON.valueToTree(l);
    assertThat(json.path("server").path("available").asBoolean()).isFalse();
    assertThat(json.path("server").path("reason").asString()).isEqualTo("not_generated");
    assertThat(json.path("ui").path("components").isArray()).isTrue();
  }

  @Test
  @DisplayName(
      "T-API-013a a generated list (array or {components}) is read, sorted by name, blank"
          + " versions and licenses are null, texts are cut at 256 characters")
  void generated() throws IOException {
    write(
        "server",
        "[{\"name\":\"org.slf4j:slf4j-api\",\"version\":\"2.0.17\",\"license\":\"MIT\"},"
            + "{\"name\":\"com.zaxxer:HikariCP\",\"version\":\"6.3.0\",\"license\":\"Apache-2.0\"}]");
    write(
        "ui",
        "{\"components\":[{\"name\":\"react\",\"version\":\"19.2.0\",\"license\":\"MIT\"},"
            + "{\"name\":\""
            + "x".repeat(300)
            + "\",\"version\":\" \"}]}");
    LicenseCatalog c = catalog();
    AboutViews.Section server = c.section("server");
    assertThat(server.available()).isTrue();
    assertThat(server.reason()).isNull();
    assertThat(server.components())
        .extracting(AboutViews.Component::name)
        .containsExactly("com.zaxxer:HikariCP", "org.slf4j:slf4j-api");
    assertThat(server.components().get(0).license()).isEqualTo("Apache-2.0");
    AboutViews.Section ui = c.section("ui");
    assertThat(ui.available()).isTrue();
    assertThat(ui.components()).hasSize(2);
    AboutViews.Component longName = ui.components().get(1);
    assertThat(longName.name()).hasSize(LicenseCatalog.MAX_TEXT);
    assertThat(longName.version()).isNull();
    assertThat(longName.license()).isNull();
    assertThat(c.section("agent").reason()).isEqualTo("not_generated");
  }

  @Test
  @DisplayName(
      "T-API-013a a list of the wrong form (not JSON, not an array, a component without a name)"
          + " is unreadable, never a partial list")
  void unreadable() throws IOException {
    write("server", "not json");
    write("ui", "{\"name\":\"react\"}");
    write("agent", "[{\"version\":\"1.0\"}]");
    LicenseCatalog c = catalog();
    for (String part : new String[] {"server", "ui", "agent"}) {
      AboutViews.Section s = c.section(part);
      assertThat(s.available()).as(part).isFalse();
      assertThat(s.reason()).as(part).isEqualTo("unreadable");
      assertThat(s.components()).as(part).isEmpty();
    }
  }

  @Test
  @DisplayName("T-API-013a more than 5,000 components: the first 5,000, truncated=true")
  void truncated() throws IOException {
    write(
        "agent",
        IntStream.range(0, LicenseCatalog.MAX_COMPONENTS + 3)
            .mapToObj(i -> "{\"name\":\"c" + i + "\",\"version\":\"1\",\"license\":\"MIT\"}")
            .collect(Collectors.joining(",", "[", "]")));
    AboutViews.Section s = catalog().section("agent");
    assertThat(s.available()).isTrue();
    assertThat(s.truncated()).isTrue();
    assertThat(s.components()).hasSize(LicenseCatalog.MAX_COMPONENTS);
  }

  @Test
  @DisplayName(
      "T-API-013a the about payload: version, commit, protocol_version, agent_versions[{version,"
          + " count}], uptime_s, support_policy_url as snake_case JSON")
  void aboutShape() {
    AboutViews.About about =
        new AboutViews.About(
            "1.0.0",
            "abc1234",
            1,
            java.util.List.of(
                new AboutViews.AgentVersion("1.0.0", 3), new AboutViews.AgentVersion(null, 1)),
            42,
            AboutController.SUPPORT_POLICY);
    JsonNode json = JSON.valueToTree(about);
    assertThat(json.path("version").asString()).isEqualTo("1.0.0");
    assertThat(json.path("commit").asString()).isEqualTo("abc1234");
    assertThat(json.path("protocol_version").asInt()).isEqualTo(1);
    assertThat(json.path("agent_versions").get(0).path("version").asString()).isEqualTo("1.0.0");
    assertThat(json.path("agent_versions").get(0).path("count").asLong()).isEqualTo(3);
    assertThat(json.path("agent_versions").get(1).path("version").isNull()).isTrue();
    assertThat(json.path("uptime_s").asLong()).isEqualTo(42);
    assertThat(json.path("support_policy_url").asString()).doesNotContain("://");
  }
}
