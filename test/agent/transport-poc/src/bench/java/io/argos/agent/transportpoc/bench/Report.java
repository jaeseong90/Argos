  private void environment(List<String> out) {
    out.add("## Environment");
    out.add("");
    out.add("- Machine: " + TransportBench.machine());
    out.add(
        "- Repetitions per resource measurement: "
            + options.repetitions()
            + " (JDK 21 and 8, agents alternating)");
    for (Map.Entry<String, Path> jdk : options.jdks().entrySet()) {
      out.add(
          "- JDK "
              + jdk.getKey()
              + ": "
              + Jdks.version(jdk.getValue())
              + " (`"
              + jdk.getValue()
              + "`)");
    }
    List<Long> before = new ArrayList<>();
    List<Long> during = new ArrayList<>();
    for (HostRun.Result r : results) {
      if (r.cpuBefore() >= 0) {
        before.add(Math.round(r.cpuBefore()));
      }
      if (r.cpuDuring() >= 0) {
        during.add(Math.round(r.cpuDuring()));
      }
    }
    out.add(
        "- Machine CPU load right before a run (percent, all processes): min %d / median %d / max %d; during runs: median %d / max %d (%d runs)"
            .formatted(
                min(before),
                median(before),
                max(before),
                median(during),
                max(during),
                results.size()));
    out.add("");
  }

  private void jarTable(List<String> out) {
    out.add("## Jars");
    out.add("");
    out.add(
        "| jar | bytes | MB | vs base | classes | own | shaded | Unsafe-ref classes | JUL-ref classes | check-shading | failed checks | own relocated literals |");
    out.add("|---|---|---|---|---|---|---|---|---|---|---|---|");
    long base = jars.get("base").size();
    for (Map.Entry<String, JarFacts> e : jars.entrySet()) {
      JarFacts j = e.getValue();
      out.add(
          "| %s | %,d | %.2f | %+,d | %,d | %,d | %,d | %d | %d | %s | %s | %d |"
              .formatted(
                  e.getKey(),
                  j.size(),
                  j.size() / 1_000_000.0,
                  j.size() - base,
                  j.classes(),
                  j.ownClasses(),
                  j.shadedClasses(),
                  j.unsafeClasses().size(),
                  j.julClasses().size(),
                  j.checkShading(),
                  j.checkShadingFailures().stream()
                      .map(f -> f.replaceAll("^FAIL \\[([^\\]]*)\\].*$", "$1"))
                      .toList(),
                  j.ownRelocatedLiterals()));
    }
    out.add("");
    for (Map.Entry<String, JarFacts> e : jars.entrySet()) {
      JarFacts j = e.getValue();
      if (!j.unsafeClasses().isEmpty()) {
        out.add(
            "- `"
                + e.getKey()
                + "` classes referencing sun/misc/Unsafe: "
                + String.join(", ", j.unsafeClasses()));
      }
      if (!j.ownRelocatedLiteralLines().isEmpty()) {
        out.add(
            "- `"
                + e.getKey()
                + "` own-code literals rewritten by relocation: "
                + String.join("; ", j.ownRelocatedLiteralLines()));
      }
    }
    out.add("");
  }

  private void libraryTable(List<String> out) {
    out.add("## Compressed size by library (KB, classes)");
    out.add("");
    Set<String> libraries = new TreeSet<>();
    jars.values().forEach(j -> libraries.addAll(j.libraries().keySet()));
    StringBuilder header = new StringBuilder("| library |");
    StringBuilder rule = new StringBuilder("|---|");
    for (String id : jars.keySet()) {
      header.append(' ').append(id).append(" |");
      rule.append("---|");
    }
    out.add(header.toString());
    out.add(rule.toString());
    for (String library : libraries) {
      StringBuilder row = new StringBuilder("| " + library + " |");
      for (JarFacts j : jars.values()) {
        long[] t = j.libraries().get(library);
        row.append(t == null ? " - |" : " %,d (%d) |".formatted(t[0] / 1024, t[2]));
      }
      out.add(row.toString());
    }
    out.add("");
  }

  private void resourceTable(List<String> out, String jdk) {
    List<HostRun.Result> runs = select("resources", jdk);
    if (runs.isEmpty()) {
      return;
    }
    out.add("## Resources on JDK " + jdk + " (medians over repetitions, host app 10 s)");
    out.add("");
    out.add(
        "| agent | runs | main at ms | startup vs none ms | first batch ms | metaspace MiB | vs none MiB | vs base MiB | classes | vs none | threads | agent threads | transport threads | direct max B | JUL loggers | temp files created | batches | CPU before % |");
    out.add("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
    Map<String, List<HostRun.Result>> byAgent = byAgent(runs);
    long noneMain = medianOf(byAgent.get("none"), r -> r.hostLong("main.uptime.ms"));
    long noneMeta = medianOf(byAgent.get("none"), r -> r.hostLong("metaspace.used"));
    long baseMeta = medianOf(byAgent.get("base"), r -> r.hostLong("metaspace.used"));
    long noneClasses = medianOf(byAgent.get("none"), r -> r.hostLong("classes.loaded"));
    Set<String> baseThreads = agentThreads(byAgent.get("base"), jdk);
    for (Map.Entry<String, List<HostRun.Result>> e : byAgent.entrySet()) {
      List<HostRun.Result> list = e.getValue();
      long main = medianOf(list, r -> r.hostLong("main.uptime.ms"));
      long meta = medianOf(list, r -> r.hostLong("metaspace.used"));
      long classes = medianOf(list, r -> r.hostLong("classes.loaded"));
      Set<String> threads = e.getKey().equals("none") ? Set.of() : agentThreads(list, jdk);
      Set<String> transport = new TreeSet<>(threads);
      transport.removeAll(baseThreads);
      out.add(
          "| %s | %d | %d | %+d | %s | %.1f | %+.1f | %+.1f | %,d | %+,d | %d | %s | %s | %,d | %d | %s | %d | %d |"
              .formatted(
                  e.getKey(),
                  list.size(),
                  main,
                  main - noneMain,
                  e.getKey().equals("none") || e.getKey().equals("base")
                      ? "-"
                      : Long.toString(medianOf(list, HostRun.Result::firstBatchMillis)),
                  meta / 1048576.0,
                  (meta - noneMeta) / 1048576.0,
                  (meta - baseMeta) / 1048576.0,
                  classes,
                  classes - noneClasses,
                  medianOf(list, r -> r.hostLong("threads.count")),
                  threads.isEmpty() ? "-" : threads.size() + ": " + String.join(", ", threads),
                  e.getKey().equals("none") || e.getKey().equals("base")
                      ? "-"
                      : transport.size()
                          + (transport.isEmpty() ? "" : ": " + String.join(", ", transport)),
                  list.stream().mapToLong(r -> r.hostLong("direct.max")).max().orElse(-1),
                  medianOf(list, r -> r.hostLong("jul.agent.loggers")),
                  tempSummary(list),
                  medianOf(list, r -> r.events().size()),
                  medianOf(list, r -> Math.round(r.cpuBefore()))));
    }
    out.add("");
  }

  private void functionTable(List<String> out) {
    out.add("## Function by JDK (batches delivered, negotiated TLS, or why not)");
    out.add("");
    List<String> columns = new ArrayList<>();
    for (String jdk : List.of("8u242", "8u252", "8", "11", "17", "21", "25", "25 deny")) {
      String name = jdk.replace(" deny", "");
      if (options.jdks().containsKey(name)) {
        columns.add(jdk);
      }
    }
    out.add("| agent | " + String.join(" | ", columns) + " |");
    out.add("|---|" + "---|".repeat(columns.size()));
    for (String agent : options.variants().keySet()) {
      StringBuilder row = new StringBuilder("| " + agent + " |");
      for (String column : columns) {
        HostRun.Result r = functionRun(agent, column);
        row.append(' ').append(r == null ? "not run" : outcome(r)).append(" |");
      }
      out.add(row.toString());
    }
    out.add("");
    for (String column : columns) {
      String name = column.replace(" deny", "");
      out.add("- " + column + ": " + Jdks.version(options.jdks().get(name)));
    }
    out.add("");
  }

  private HostRun.Result functionRun(String agent, String column) {
    boolean deny = column.endsWith(" deny");
    String jdk = column.replace(" deny", "");
    for (HostRun.Result r : results) {
      boolean rDeny = r.spec().jvmOptions().stream().anyMatch(o -> o.contains("=deny"));
      if (!r.spec().agent().equals(agent) || !r.spec().jdk().equals(jdk) || rDeny != deny) {
        continue;
      }
      String s = r.spec().scenario();
      if (s.equals("function")
          || s.equals("jdk25")
          || (s.equals("resources") && r.repetition() == 1)) {
        return r;
      }
    }
    return null;
  }

  private static String outcome(HostRun.Result r) {
    String disabled = r.agentLine("transport-poc disabled");
    if (!r.events().isEmpty()) {
      return "OK %d batches, %s".formatted(r.events().size(), r.events().get(0).tls());
    }
    if (disabled != null) {
      return "disabled: " + shorten(disabled.substring(disabled.indexOf("could not start")), 110);
    }
    String failed = r.agentLine("transport-poc failed");
    if (failed != null) {
      return "FAIL: " + shorten(failed.substring(failed.indexOf("transport-poc failed")), 110);
    }
    List<String> warnings = r.agentLines("WARN");
    if (!warnings.isEmpty()) {
      String first = warnings.get(0);
      return "FAIL: " + shorten(first.substring(Math.max(0, first.indexOf("] ") + 2)), 110);
    }
    return "FAIL exit=" + r.exitCode();
  }

  private void jdk25Table(List<String> out) {
    List<HostRun.Result> runs = new ArrayList<>(select("jdk25", "25"));
    if (runs.isEmpty()) {
      return;
    }
    out.add(
        "## JDK 25: sun.misc.Unsafe warnings (default = warn) and --sun-misc-unsafe-memory-access=deny");
    out.add("");
    out.add(
        "| agent | mode | Unsafe warning lines | batches | agent ERROR | agent WARN | other stderr lines | first stderr line |");
    out.add("|---|---|---|---|---|---|---|---|");
    for (HostRun.Result r : runs) {
      boolean deny = r.spec().jvmOptions().stream().anyMatch(o -> o.contains("=deny"));
      List<String> stderr = r.foreignStderr();
      out.add(
          "| %s | %s | %d | %d | %d | %d | %d | %s |"
              .formatted(
                  r.spec().agent(),
                  deny ? "deny" : "default (warn)",
                  r.unsafeWarnings().size(),
                  r.events().size(),
                  r.agentLines("ERROR").size(),
                  r.agentLines("WARN").size(),
                  stderr.size() - r.unsafeWarnings().size(),
                  stderr.isEmpty()
                      ? "-"
                      : "`" + shorten(stderr.get(0), 140).replace("|", "/") + "`"));
    }
    out.add("");
  }

  private void classLoadTable(List<String> out) throws IOException {
    List<HostRun.Result> runs = new ArrayList<>();
    for (HostRun.Result r : results) {
      if (r.spec().scenario().equals("classload")) {
        runs.add(r);
      }
    }
    if (runs.isEmpty()) {
      return;
    }
    out.add("## Classes loaded at run time (agent jar classes; Unsafe- and JUL-referencing ones)");
    out.add("");
    out.add(
        "| agent | JDK | agent classes loaded | Unsafe-ref classes loaded | JUL loggers created by the agent | Unsafe-ref classes loaded (names) |");
    out.add("|---|---|---|---|---|---|");
    for (HostRun.Result r : runs) {
      Set<String> loaded = loadedClasses(r);
      Set<String> agentClasses = new TreeSet<>();
      for (String name : loaded) {
        if (name.startsWith("io.argos.agent.")) {
          agentClasses.add(name);
        }
      }
      JarFacts facts = jars.get(r.spec().agent());
      List<String> unsafeLoaded = new ArrayList<>();
      List<String> unsafeClasses = facts == null ? List.of() : facts.unsafeClasses();
      for (String name : unsafeClasses) {
        if (loaded.contains(name)) {
          unsafeLoaded.add(name.replace("io.argos.agent.shaded.", ""));
        }
      }
      out.add(
          "| %s | %s | %,d | %d of %d | %s | %s |"
              .formatted(
                  r.spec().agent(),
                  r.spec().jdk(),
                  agentClasses.size(),
                  unsafeLoaded.size(),
                  unsafeClasses.size(),
                  julSummary(r),
                  unsafeLoaded.isEmpty() ? "-" : String.join(", ", unsafeLoaded)));
    }
    out.add("");
  }

  /** Temporary entries created during the runs (union of names, '#' for digits), T-BLD-006. */
  private static String tempSummary(List<HostRun.Result> runs) {
    Set<String> names = new TreeSet<>();
    int total = 0;
    for (HostRun.Result r : runs) {
      names.addAll(r.tmpCreated());
      names.addAll(r.tmpEntries());
      total += r.tmpCreated().size();
    }
    return names.isEmpty() ? "0" : total + " (" + String.join(", ", names) + ")";
  }

  private static String julSummary(HostRun.Result r) {
    String names = r.host().getProperty("jul.agent.logger.names", "");
    long count = r.hostLong("jul.agent.loggers");
    if (count <= 0) {
      return Long.toString(count);
    }
    List<String> list = Arrays.asList(names.split("\\|", -1));
    return count
        + " ("
        + String.join(", ", list.subList(0, Math.min(4, list.size())))
            .replace("io.argos.agent.shaded.", "")
        + (list.size() > 4 ? ", ..." : "")
        + ")";
  }

  /** Classes named in -Xlog:class+load (JDK 9+) or -verbose:class (JDK 8) output. */
  static Set<String> loadedClasses(HostRun.Result r) throws IOException {
    Set<String> names = new LinkedHashSet<>();
    Path xlog = r.dir().resolve("classload.txt");
    List<String> lines = Files.exists(xlog) ? HostRun.lines(xlog) : r.stdout();
    for (String line : lines) {
      int start;
      if (line.startsWith("[Loaded ")) {
        start = "[Loaded ".length();
      } else {
        int marker = line.indexOf("[class,load] ");
        if (marker < 0) {
          continue;
        }
        start = marker + "[class,load] ".length();
      }
      int end = line.indexOf(' ', start);
      names.add(end < 0 ? line.substring(start) : line.substring(start, end));
    }
    return names;
  }

  private void c23Table(List<String> out) {
    List<HostRun.Result> runs = new ArrayList<>();
    for (HostRun.Result r : results) {
      boolean reference =
          r.spec().scenario().equals("resources")
              && r.repetition() == 1
              && r.spec().jdk().equals("21")
              && r.spec().agent().startsWith("grpc-netty");
      if (r.spec().scenario().equals("c23") || reference) {
        runs.add(r);
      }
    }
    if (runs.isEmpty()) {
      return;
    }
    out.add("## ADR-0003 C-23: relocated Netty properties at run time");
    out.add("");
    out.add(
        "| run | application -D | agent Netty (agent log) | host io.netty.noUnsafe | host io.argos.agent.shaded.io.netty.noUnsafe | host ...allocator.type (orig / relocated) |");
    out.add("|---|---|---|---|---|---|");
    for (HostRun.Result r : runs) {
      String ack = r.agentLine("transport-poc first-ack");
      String netty = ack == null ? "-" : ack.substring(Math.max(0, ack.indexOf("netty ")));
      out.add(
          "| %s | %s | %s | %s | %s | %s / %s |"
              .formatted(
                  r.spec().scenario() + " " + r.spec().agent(),
                  r.spec().jvmOptions().isEmpty() ? "-" : String.join(" ", r.spec().jvmOptions()),
                  netty,
                  r.host().getProperty("prop.io.netty.noUnsafe"),
                  r.host().getProperty("prop.io.argos.agent.shaded.io.netty.noUnsafe"),
                  r.host().getProperty("prop.io.netty.allocator.type"),
                  r.host().getProperty("prop.io.argos.agent.shaded.io.netty.allocator.type")));
    }
    out.add("");
  }

