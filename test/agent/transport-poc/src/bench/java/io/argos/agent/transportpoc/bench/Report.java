  private void gateTable(List<String> out) {
    out.add("## Gate 0 P-3 adoption criteria (02 §11 P-3)");
    out.add("");
    out.add(
        "| agent | jar <= 15 MB | startup +<= 2 s (JDK 21 / 8) | agent threads <= 6 | direct <= 8 MiB | Unsafe warnings 0 (JDK 25) | JDK 25 deny works | verdict |");
    out.add("|---|---|---|---|---|---|---|---|");
    for (String agent : options.variants().keySet()) {
      List<String> fails = new ArrayList<>();
      long size = jars.get(agent).size();
      boolean jarOk = size <= TransportBench.GATE_JAR_BYTES;
      StringBuilder startup = new StringBuilder();
      boolean startupOk = true;
      int maxThreads = 0;
      long maxDirect = -1;
      for (String jdk : List.of("21", "8")) {
        Map<String, List<HostRun.Result>> byAgent = byAgent(select("resources", jdk));
        if (!byAgent.containsKey(agent) || !byAgent.containsKey("none")) {
          continue;
        }
        long delta =
            medianOf(byAgent.get(agent), r -> r.hostLong("main.uptime.ms"))
                - medianOf(byAgent.get("none"), r -> r.hostLong("main.uptime.ms"));
        startupOk &= delta <= TransportBench.GATE_STARTUP_MILLIS;
        startup.append(startup.length() == 0 ? "" : " / ").append("%+d ms".formatted(delta));
        maxThreads = Math.max(maxThreads, agentThreads(byAgent.get(agent), jdk).size());
        maxDirect =
            Math.max(
                maxDirect,
                byAgent.get(agent).stream()
                    .mapToLong(r -> r.hostLong("direct.max"))
                    .max()
                    .orElse(-1));
      }
      boolean threadsOk = maxThreads <= TransportBench.GATE_THREADS;
      boolean directOk = maxDirect <= TransportBench.GATE_DIRECT_BYTES;
      HostRun.Result warn = functionRun(agent, "25");
      HostRun.Result deny = functionRun(agent, "25 deny");
      int warnings =
          warn == null
              ? -1
              : warn.unsafeWarnings().size() + (deny == null ? 0 : deny.unsafeWarnings().size());
      boolean warningsOk = warnings == 0;
      boolean denyOk = deny != null && !deny.events().isEmpty() && deny.foreignStderr().isEmpty();
      if (!jarOk) {
        fails.add("jar");
      }
      if (!startupOk) {
        fails.add("startup");
      }
      if (!threadsOk) {
        fails.add("threads");
      }
      if (!directOk) {
        fails.add("direct");
      }
      if (!warningsOk) {
        fails.add("Unsafe warnings");
      }
      if (!denyOk) {
        fails.add("deny");
      }
      out.add(
          "| %s | %s %.2f MB | %s %s | %s %d | %s %,d B | %s %s | %s | %s |"
              .formatted(
                  agent,
                  mark(jarOk),
                  size / 1_000_000.0,
                  mark(startupOk),
                  startup,
                  mark(threadsOk),
                  maxThreads,
                  mark(directOk),
                  maxDirect,
                  mark(warningsOk),
                  warnings < 0 ? "not run" : Integer.toString(warnings),
                  deny == null ? "not run" : mark(denyOk) + " " + outcome(deny).replace("|", "/"),
                  fails.isEmpty() ? "PASS" : "FAIL (" + String.join(", ", fails) + ")"));
    }
    out.add("");
    out.add(
        "Startup = median difference of `main()` entry time (JVM uptime) against the run without agent. Agent threads = threads named `argos-*` plus threads that never appear without agent on that JDK.");
    out.add("");
  }

