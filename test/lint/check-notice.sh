#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# check-notice.sh: third-party source code in the repository is listed in NOTICE (T-BLD-012, O-L05,
# 19 §5.1). Code taken from another open-source project keeps its original copyright header and is
# named, with its source, in the NOTICE section "Third-party source code adapted in this repository"
# (CLAUDE.md, CONTRIBUTING).
#
#   Files checked: the source file set of check-spdx.sh (*.java *.kt *.kts *.ts *.tsx *.mts *.cts
#                  *.js *.jsx *.mjs *.cjs *.proto *.sql *.sh *.bash *.py *.ps1 *.bat *.cmd *.yml
#                  *.yaml *.toml *.properties *.css *.html; git ls-files, otherwise find)
#   Third-party:   a file whose first 30 lines hold a copyright line with a year that does not name
#                  "Argos APM contributors" ("Copyright 2015 Example Authors", "(c) 2019 X") or an
#                  SPDX-License-Identifier other than Apache-2.0, or that holds a borrowed-code
#                  marker anywhere: "Adapted from" (capital A), or "adapted/derived/ported/copied
#                  from" followed by an http(s) URL on the same line
#   NOTICE:        the section after the heading "Third-party source code adapted in this
#                  repository" (up to the next heading, a line followed by a row of dashes) is
#                  either "None." or one entry per line: the repository path at column 0 (a file,
#                  or a directory ending in "/"), then the source and its license, e.g.
#                    ui/src/lib/foo.ts  adapted from https://github.com/x/foo v1.2 (MIT)
#                  Indented lines continue the entry above.
#   Rules:         every third-party file is listed (as itself or below a listed directory); every
#                  listed path exists; a listed file still carries its original copyright header or
#                  marker (O-L05); "None." only when no file is third-party
#   Not checked:   generated tool files (GENERATED below), which are not adapted source code, and
#                  this script, whose comments and patterns spell out the markers
#
# Usage:  test/lint/check-notice.sh [root]   (default: the repository root, two levels up)
# Exit:   0 when NOTICE and the sources agree, 1 on a violation, 2 on a usage error.

set -euo pipefail
export LC_ALL=C

readonly HEADER_LINES=30
readonly EXTENSIONS_RE='\.(java|kt|kts|ts|tsx|mts|cts|js|jsx|mjs|cjs|proto|sql|sh|bash|py|ps1|bat|cmd|yml|yaml|toml|properties|css|html)$'
readonly SECTION="Third-party source code adapted in this repository"
# Generated by tools, never edited: the Gradle wrapper scripts (Gradle, Apache-2.0).
readonly GENERATED=("gradlew.bat" "gradlew")
readonly SELF="test/lint/check-notice.sh"

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="${1:-$script_dir/../..}"
if [[ $# -gt 1 || ! -d "$root" ]]; then
  echo "usage: $0 [root]" >&2
  exit 2
fi
root="$(cd "$root" && pwd)"
cd "$root"
if [[ ! -f NOTICE ]]; then
  echo "check-notice: FAILED: $root/NOTICE not found" >&2
  exit 1
fi

work="$(mktemp -d "${TMPDIR:-/tmp}/argos-check-notice.XXXXXX")"
trap 'rm -rf "$work"' EXIT

# --- file set (as check-spdx.sh) -------------------------------------------------------------
if git -C "$root" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  mode="git ls-files"
  git -C "$root" ls-files -z --cached --others --exclude-standard | tr '\0' '\n' >"$work/all.txt"
else
  mode="find"
  find . \( -name .git -o -name build -o -name node_modules -o -name .gradle -o -name .kotlin \
    -o -path ./ui/dist -o -name coverage -o -name test-results -o -name playwright-report \
    -o -name .idea -o -name .vscode \) -prune -o -type f -print |
    sed 's#^\./##' >"$work/all.txt"
fi
grep -E "$EXTENSIONS_RE" "$work/all.txt" | sort -u >"$work/candidates.txt" || true
: >"$work/files.txt"
while IFS= read -r file; do
  [[ -f "$file" && -s "$file" ]] || continue
  [[ "$file" == "$SELF" ]] && continue
  for generated in "${GENERATED[@]}"; do
    [[ "$file" == "$generated" ]] && continue 2
  done
  echo "$file" >>"$work/files.txt"
done <"$work/candidates.txt"

# --- third-party files -----------------------------------------------------------------------
# One awk process per xargs batch: "<file>\t<reason>" for the first signal of each file.
: >"$work/flagged.tsv"
if [[ -s "$work/files.txt" ]]; then
  # shellcheck disable=SC2016 # the single-quoted text is an awk program
  tr '\n' '\0' <"$work/files.txt" |
    xargs -0 awk -v max="$HEADER_LINES" '
      FNR == 1 { done = 0 }
      done { next }
      {
        line = $0
        sub(/\r$/, "", line)
        lower = tolower(line)
      }
      # A comment line of the header (not an identifier inside a string literal).
      FNR <= max && line ~ /^[ \t]*(\/\/|\/\*+|\*|#|--|<!--|@?[Rr][Ee][Mm]|::)[ \t]*SPDX-License-Identifier:/ {
        id = line
        sub(/^.*SPDX-License-Identifier:[ \t]*/, "", id)
        sub(/[ \t]*(\*\/|-->).*$/, "", id)
        sub(/[ \t]+$/, "", id)
        if (id != "Apache-2.0") { printf "%s\tSPDX-License-Identifier: %s\n", FILENAME, id; done = 1; next }
      }
      FNR <= max && lower ~ /(copyright|\(c\)|©)[ \t]*(\(c\)|©)?[ \t]*[12][0-9][0-9][0-9]/ && index(line, "Argos APM contributors") == 0 {
        text = line
        sub(/^[ \t]*(\/\/|\/\*+|\*|#|--|<!--|@?rem|::)?[ \t]*/, "", text)
        printf "%s\tcopyright header: %s\n", FILENAME, substr(text, 1, 80); done = 1; next
      }
      line ~ /Adapt[e]d from/ || lower ~ /(adapted|derived|ported|copied) from[^a-z].*https?:\/\// {
        text = line
        sub(/^[ \t]*(\/\/|\/\*+|\*|#|--|<!--)?[ \t]*/, "", text)
        printf "%s\tmarker: %s\n", FILENAME, substr(text, 1, 80); done = 1; next
      }' >"$work/flagged.tsv"
fi
sort -o "$work/flagged.tsv" "$work/flagged.tsv"

# --- NOTICE section --------------------------------------------------------------------------
# Lines of the section, CR removed; the heading is followed by a row of dashes, and the section ends
# at the next line that is followed by such a row.
awk -v section="$SECTION" '
  { sub(/\r$/, ""); lines[NR] = $0 }
  END {
    start = 0
    for (i = 1; i <= NR; i++) if (lines[i] == section && lines[i + 1] ~ /^-+$/) { start = i + 2; break }
    if (start == 0) { print "MISSING"; exit }
    for (i = start; i <= NR; i++) {
      if (i < NR && lines[i] != "" && lines[i + 1] ~ /^-+$/) break
      print lines[i]
    }
  }' NOTICE >"$work/section.txt"

: >"$work/problems.txt"
if [[ "$(head -n1 "$work/section.txt")" == "MISSING" ]]; then
  echo "NOTICE: no section \"$SECTION\" (heading followed by a row of dashes)" >>"$work/problems.txt"
  : >"$work/section.txt"
fi
none=0
grep -qx 'None\.' "$work/section.txt" && none=1
# Entries: a path at column 0 (not "None."), the first whitespace-separated token.
grep -E '^[^[:space:]]' "$work/section.txt" | grep -vx 'None\.' | awk '{ print $1 }' | sort -u >"$work/listed.txt" || true

if ((none == 1)) && [[ -s "$work/listed.txt" ]]; then
  echo "NOTICE: \"$SECTION\" says \"None.\" and lists paths" >>"$work/problems.txt"
fi
if ((none == 0)) && [[ ! -s "$work/listed.txt" ]] && [[ -s "$work/section.txt" ]]; then
  echo "NOTICE: \"$SECTION\" is neither \"None.\" nor a list of paths" >>"$work/problems.txt"
fi

# Every listed path exists; a listed file still carries its header or marker.
while IFS= read -r listed; do
  if [[ "$listed" == */ ]]; then
    [[ -d "$listed" ]] || echo "NOTICE: listed directory $listed does not exist" >>"$work/problems.txt"
  elif [[ ! -f "$listed" ]]; then
    echo "NOTICE: listed file $listed does not exist" >>"$work/problems.txt"
  elif grep -qx "$listed" "$work/files.txt" && ! cut -f1 "$work/flagged.tsv" | grep -qxF "$listed"; then
    echo "$listed: listed in NOTICE but carries no original copyright header or borrowed-code marker (O-L05)" >>"$work/problems.txt"
  fi
done <"$work/listed.txt"

# Every third-party file is listed.
while IFS=$'\t' read -r file reason; do
  covered=0
  while IFS= read -r listed; do
    if [[ "$file" == "$listed" || ("$listed" == */ && "$file" == "$listed"*) ]]; then
      covered=1
      break
    fi
  done <"$work/listed.txt"
  ((covered == 1)) || echo "$file: third-party code ($reason) not listed in NOTICE \"$SECTION\"" >>"$work/problems.txt"
done <"$work/flagged.tsv"

checked="$(wc -l <"$work/files.txt" | tr -d ' ')"
adapted="$(wc -l <"$work/flagged.tsv" | tr -d ' ')"
if [[ -s "$work/problems.txt" ]]; then
  echo "check-notice: FAILED: NOTICE and the third-party source code in the repository disagree:"
  sed 's/^/    /' "$work/problems.txt"
  echo "check-notice: $(wc -l <"$work/problems.txt" | tr -d ' ') problem(s) ($checked files, $mode, $adapted third-party)"
  exit 1
fi
echo "check-notice: OK ($checked files, $mode, $adapted third-party)"
