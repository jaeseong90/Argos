package io.argos.storage.generator.model;

import io.argos.storage.generator.model.Topology.ErrorGroup;
import io.argos.storage.generator.model.Topology.ExtHost;
import io.argos.storage.generator.model.Topology.Instance;
import io.argos.storage.generator.model.Topology.Service;
import io.argos.storage.generator.model.Topology.SqlStatement;
import io.argos.storage.generator.rows.Row;
import io.argos.storage.generator.rows.RowBinaryWriter;
import java.util.ArrayList;
import java.util.List;

/**
 * One generated transaction (one xlog row) with the SQL executions and outgoing calls it made. The
 * agent-side fields are set by {@link TransactionFactory}; the server-side fields ({@link
 * #receivedMs}, {@link #tsMs}, {@link #late}, {@link #clamped}) by the timestamp guard of the
 * simulation (D-15).
 */
public final class Transaction implements Row {

  /** {@code kind} Enum8 values (13 §2). */
  public static final int HTTP = 1;

  public static final int BATCH = 2;

  /** xlog.flags bits (C-17): virtual thread, leaked, summarized. */
  public static final int FLAG_VIRTUAL_THREAD = 1;

  public static final int FLAG_LEAKED = 2;
  public static final int FLAG_SUMMARIZED = 4;

  /** A run of consecutive executions of one SQL statement (one profile step when captured). */
  public static final class SqlRun {
    public final SqlStatement sql;
    public final int count;
    public int startOffsetMs;
    public int totalMs;
    public int execMs;
    public int fetchMs;
    public int rows;
    public boolean error;
    public int batchSize;

    SqlRun(SqlStatement sql, int count) {
      this.sql = sql;
      this.count = count;
    }

    /** Duration (exec + fetch) of execution {@code i} of the run; the parts sum to totalMs. */
    public int executionMs(int i) {
      int base = totalMs / count;
      return base + (i < totalMs % count ? 1 : 0);
    }

    /** Execute part of execution {@code i}; the parts sum to execMs. */
    public int executionExecMs(int i) {
      int base = execMs / count;
      return base + (i < execMs % count ? 1 : 0);
    }

    /** Rows fetched by execution {@code i}; the parts sum to rows. */
    public int executionRows(int i) {
      int base = rows / count;
      return base + (i < rows % count ? 1 : 0);
    }

    /** End offset (from the transaction start) of execution {@code i}. */
    public int executionEndOffsetMs(int i) {
      int end = startOffsetMs;
      for (int k = 0; k <= i; k++) {
        end += executionMs(k);
      }
      return end;
    }
  }

  /** One outgoing call. */
  public static final class ExtCall {
    public final ExtHost host;
    public final int pathIndex;
    public int startOffsetMs;
    public int durationMs;
    public int status;
    public boolean error;
    public boolean timeout;
    public boolean connectFail;
    public int responseBytes;
    public long spanId;
    public Transaction child;

    ExtCall(ExtHost host, int pathIndex) {
      this.host = host;
      this.pathIndex = pathIndex;
    }
  }

  public final Instance instance;
  public final Service service;
  public final int kind;
  public final long startTrueMs;
  public final long tsAgentMs;
  public long txId;
  public int elapsedMs;
  public boolean error;
  public ErrorGroup errorGroup;
  public int httpStatus;
  public final byte[] traceId = new byte[16];
  public long spanId;
  public long parentSpanId;
  public boolean incomingTrace;

  /** The trace id was generated by an Argos agent (Unix seconds in bytes 0..3). */
  public boolean argosTrace;

  public int callerAppId;
  public long versionId;
  public int remoteIpv4;
  public String userId = "";
  public String requestId = "";
  public final List<SqlRun> sqlRuns = new ArrayList<>();
  public int sqlCount;
  public int sqlTimeMs;
  public long[] sqlIds = new long[0];
  public int dbcTimeMs;
  public int dbcOffsetMs;
  public final List<ExtCall> extCalls = new ArrayList<>();
  public int extTimeMs;
  public int cpuTimeMs;
  public long allocBytes;
  public boolean profileCaptured;
  public boolean streaming;
  public boolean timeoutFlag;
  public int dispatchCount;
  public int flags;
  public int preMs;
  public final List<Transaction> children = new ArrayList<>();

  /** Set by the simulation (server receive time and timestamp guard). */
  public long receivedMs;

  public long tsMs;
  public boolean late;
  public boolean clamped;

  Transaction(Instance instance, Service service, int kind, long startTrueMs) {
    this.instance = instance;
    this.service = service;
    this.kind = kind;
    this.startTrueMs = startTrueMs;
    this.tsAgentMs = instance.agentClock(startTrueMs);
  }

  /** True end of the transaction. */
  public long endTrueMs() {
    return startTrueMs + elapsedMs;
  }

  /** Number of outgoing calls. */
  public int extCount() {
    return extCalls.size();
  }

  @Override
  public long tsMs() {
    return tsMs;
  }

  @Override
  public void write(RowBinaryWriter w) {
    Topology.App app = instance.app;
    w.i32(app.id);
    w.string(app.env);
    w.i32(instance.id);
    w.i64(tsMs);
    w.i64(txId);
    w.u8(kind);
    w.raw(traceId);
    w.i64(spanId);
    w.i64(parentSpanId);
    w.u8(incomingTrace ? 1 : 0);
    w.i32(callerAppId);
    w.i64(service.id);
    w.i64(versionId);
    w.string(service.httpMethod);
    w.u16(httpStatus);
    w.i32(elapsedMs);
    w.u8(error ? 1 : 0);
    w.i64(error ? errorGroup.classId() : 0L);
    w.i64(error ? errorGroup.id() : 0L);
    w.u16(service.apdexTMs);
    w.ipv4Mapped(remoteIpv4);
    w.u8(1); // ip_mode masked
    w.string(userId);
    w.u8(2); // user_id_mode hashed
    w.string(requestId);
    w.u16(Math.min(sqlCount, 0xFFFF));
    w.i32(sqlTimeMs);
    w.i32(dbcTimeMs);
    w.u16(Math.min(extCount(), 0xFFFF));
    w.i32(extTimeMs);
    w.i32(cpuTimeMs);
    w.i64(allocBytes);
    w.i64(kind == BATCH ? app.threadBatchId : app.threadHttpId);
    w.u8(profileCaptured ? 1 : 0);
    w.u8(streaming ? 1 : 0);
    w.u8(timeoutFlag ? 1 : 0);
    w.u16(dispatchCount);
    w.u8(late ? 1 : 0);
    w.u16(flags);
    w.u64Array(sqlIds, sqlIds.length);
  }
}
