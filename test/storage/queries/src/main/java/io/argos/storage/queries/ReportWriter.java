package io.argos.storage.queries;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Writes the results of a run: {@code report.md} (input of docs/poc/clickhouse-benchmark.md:
 * environment, data, query times against the 13 §15 criteria, consistency results, procedures) and
 * {@code runs.tsv} (one line per statement with its system.query_log record).
 */
public final class ReportWriter {

  private ReportWriter() {}

  /** Writes report.md and runs.tsv into {@code dir}; returns the report path. */
  public static Path write(BenchResults results, Path dir) {
    try {
      Files.createDirectories(dir);
      results.settleLoad();
      Path report = dir.resolve("report.md");
      Files.writeString(report, markdown(results), StandardCharsets.UTF_8);
      Files.writeString(dir.resolve("runs.tsv"), tsv(results), StandardCharsets.UTF_8);
      return report;
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }

  /** The Markdown report. */
  public static String markdown(BenchResults r) {
    StringBuilder md = new StringBuilder();
    md.append("# Storage PoC queries Q01..Q20 (WO-03, P-4)\n\n");
    md.append(
            "Generated by test/storage/queries (QueryBench). Numbers from a shared or reduced-scale")
        .append(
            " machine are reference values; the Gate 0 criteria apply to the target environment of")
        .append(" docs/13 section 15.\n\n");
    md.append("## Environment\n\n");
    for (Map.Entry<String, String> e : r.environment().entrySet()) {
      md.append("- ").append(e.getKey()).append(": ").append(cell(e.getValue())).append('\n');
    }
    md.append('\n');
    if (r.data() != null) {
      md.append("## Data\n\n");
      table(md, r.data());
    }
    if (!r.variants().isEmpty()) {
      md.append("## Queries\n\n");
      md.append("Wall time is the client time from request to the last byte (localhost HTTP);")
          .append(
              " server time is query_duration_ms of system.query_log. Timing variants: cold 1 run")
          .append(" + warm runs, criterion on the warm median. Consistency variants: one run,")
          .append(
              " criterion on the result rows. Compressed read = ProfileEvents ReadCompressedBytes")
          .append(
              " (columns, marks and skip index files); marks = selected after the primary key and")
          .append(" skip indexes / marks of the selected parts. CPU load = machine load while the")
          .append(
              " runs ran (samples from the first after the start to the first after the end).\n\n");
      md.append(
          "| query | variant | criterion | verdict | cold ms | warm ms (median) | server ms | rows read"
              + " | MiB read | MiB compressed read | marks (of total) | memory MiB | result rows"
              + " | CPU load |\n");
      md.append("|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n");
      for (VariantResult v : r.variants()) {
        QueryLog.Entry last = v.lastServerRun();
        md.append("| ")
            .append(v.fileId())
            .append(" | ")
            .append(v.variant())
            .append(" | ")
            .append(cell(v.criterion().toString()))
            .append(" | ")
            .append(v.verdict())
            .append(" | ")
            .append(num(v.metric("cold_ms"), 1))
            .append(" | ")
            .append(num(v.metric("warm_ms"), 1))
            .append(" | ")
            .append(num(v.metric("server_warm_ms"), 0))
            .append(" | ")
            .append(last == null ? "-" : Long.toString(last.readRows()))
            .append(" | ")
            .append(last == null ? "-" : num(last.readBytes() / 1048576.0, 1))
            .append(" | ")
            .append(last == null ? "-" : num(last.readCompressedBytes() / 1048576.0, 1))
            .append(" | ")
            .append(last == null ? "-" : last.selectedMarks() + " / " + last.selectedMarksTotal())
            .append(" | ")
            .append(last == null ? "-" : num(last.memoryUsage() / 1048576.0, 1))
            .append(" | ")
            .append(num(v.metric("rows"), 0))
            .append(" | ")
            .append(pct(v.cpuLoad(r.load())))
            .append(" |\n");
      }
      md.append('\n');
      List<String> problems = new ArrayList<>();
      for (VariantResult v : r.variants()) {
        for (String violation : v.violations()) {
          problems.add(v.label() + " " + v.verdict() + ": " + violation);
        }
        if (v.note() != null) {
          problems.add(v.label() + " " + v.verdict() + ": " + v.note());
        }
        if (v.verdict() == Verdict.FAIL && v.fileId().compareTo("Q12") >= 0) {
          List<List<String>> rows = v.lastRows();
          problems.add(
              v.label() + " first mismatching rows: " + rows.subList(0, Math.min(5, rows.size())));
        }
      }
      if (!problems.isEmpty()) {
        md.append("### Findings\n\n");
        for (String p : problems) {
          md.append("- ").append(cell(p)).append('\n');
        }
        md.append('\n');
      }
    }
    if (!r.procedures().isEmpty()) {
      md.append("## Procedures\n\n");
      for (ProcedureResult p : r.procedures()) {
        md.append("### ").append(p.id()).append(": ").append(cell(p.title())).append("\n\n");
        md.append("- criterion: ")
            .append(cell(p.criterion().toString()))
            .append(", verdict: ")
            .append(p.verdict())
            .append('\n');
        for (String v : p.violations()) {
          md.append("- violation: ").append(cell(v)).append('\n');
        }
        if (!p.metrics().isEmpty()) {
          md.append("- metrics: ");
          List<String> parts = new ArrayList<>();
          p.metrics().forEach((k, v) -> parts.add(k + " = " + num(v, 4)));
          md.append(cell(String.join(", ", parts))).append('\n');
        }
        for (String n : p.notes()) {
          md.append("- ").append(cell(n)).append('\n');
        }
        md.append('\n');
        for (ProcedureResult.Table t : p.tables()) {
          table(md, t);
        }
      }
    }
    if (!r.errors().isEmpty()) {
      md.append("## Errors\n\n");
      for (String e : r.errors()) {
        md.append("- ").append(cell(e)).append('\n');
      }
      md.append('\n');
    }
    md.append("## Parameters\n\n");
    md.append("Shared parameters resolved from the data (params.sql):\n\n");
    for (Map.Entry<String, String> e : new java.util.TreeMap<>(r.parameters().asMap()).entrySet()) {
      md.append("- ")
          .append(e.getKey())
          .append(" = `")
          .append(e.getValue().replace("`", "'"))
          .append("`\n");
    }
    return md.toString();
  }

  /** One line per statement: client measurement and system.query_log record. */
  public static String tsv(BenchResults r) {
    StringBuilder out = new StringBuilder();
    out.append(
        "query_id\tlabel\tphase\taccount\twall_ms\tresult_rows\terror\tcpu_load\tserver_ms\tread_rows"
            + "\tread_bytes\tmemory_bytes\tselected_marks\tos_read_bytes\tcpu_ms\twritten_rows"
            + "\tread_compressed_bytes\tselected_marks_total\tskip_index_us\n");
    List<Measurement> all = new ArrayList<>();
    for (VariantResult v : r.variants()) {
      all.addAll(v.runs());
    }
    all.addAll(r.stepRuns().values());
    for (Measurement m : all) {
      QueryLog.Entry e = r.queryLog().get(m.queryId());
      out.append(m.queryId())
          .append('\t')
          .append(m.label())
          .append('\t')
          .append(m.phase())
          .append('\t')
          .append(m.account())
          .append('\t')
          .append(num(m.wallMs(), 2))
          .append('\t')
          .append(m.rows())
          .append('\t')
          .append(m.errorName() == null ? "" : m.errorName())
          .append('\t')
          .append(num(r.cpuLoad(m), 3))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.durationMs()))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.readRows()))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.readBytes()))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.memoryUsage()))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.selectedMarks()))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.osReadBytes()))
          .append('\t')
          .append(e == null ? "" : num(e.cpuMs(), 1))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.writtenRows()))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.readCompressedBytes()))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.selectedMarksTotal()))
          .append('\t')
          .append(e == null ? "" : Long.toString(e.skipIndexUs()))
          .append('\n');
    }
    return out.toString();
  }

  private static void table(StringBuilder md, ProcedureResult.Table t) {
    md.append("**").append(cell(t.title())).append("**\n\n");
    md.append("| ")
        .append(String.join(" | ", t.headers().stream().map(ReportWriter::cell).toList()))
        .append(" |\n");
    md.append("|").append("---|".repeat(t.headers().size())).append('\n');
    for (List<String> row : t.rows()) {
      md.append("| ")
          .append(String.join(" | ", row.stream().map(ReportWriter::cell).toList()))
          .append(" |\n");
    }
    md.append('\n');
  }

  /** Makes a value safe for a Markdown table cell (no pipes, no line breaks, no HTML). */
  static String cell(String s) {
    return s.replace("|", "\\|").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;");
  }

  static String num(double v, int decimals) {
    if (Double.isNaN(v)) {
      return "-";
    }
    if (Double.isInfinite(v)) {
      return v > 0 ? "inf" : "-inf";
    }
    return String.format(Locale.ROOT, "%." + decimals + "f", v);
  }

  static String pct(double v) {
    return Double.isNaN(v) ? "-" : String.format(Locale.ROOT, "%.0f %%", v * 100);
  }
}
