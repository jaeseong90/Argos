// TypeScript types of the REST API, generated from the committed OpenAPI contract
// (docs/api/openapi.yaml, written by ./gradlew :server:generateOpenApi; docs/19 §6.2, docs/14 §8,
// ADR-0003 C-28). The UI reaches the server only through these types and the wrapper in src/api
// (03 §3.3); src/api/generated/ is never edited by hand.
//
//   gen:api    writes src/api/generated/schema.ts
//   check:api  generates in memory and fails when the committed file differs (CI, `pnpm test`)
//
// Untrusted strings (DSN-14-13, SEC-60): every schema with `x-argos-untrusted: true` and a string
// type becomes `Untrusted` (src/api/untrusted.ts), so `string | null` becomes `Untrusted | null`,
// string arrays `Untrusted[]` and string maps `{ [key: string]: Untrusted }`. The flag of an array
// or map is carried over to its items or values first. The ESLint rule argos/untrusted-text then
// rejects such values as JSX children or attributes outside SafeText, SafeLink and CodeBlock.
//
// The output is deterministic: openapi-typescript and Prettier are pinned in package.json, the
// file uses LF and starts with the SPDX header.
//
// Usage: node scripts/gen-api.mjs [--check] [--spec <file>] [--out <file>]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';
import ts from 'typescript';

export const UNTRUSTED_EXTENSION = 'x-argos-untrusted';
export const UNTRUSTED_TYPE = 'Untrusted';

const UI_ROOT = fileURLToPath(new URL('..', import.meta.url));
export const DEFAULT_SPEC = join(UI_ROOT, '..', 'docs', 'api', 'openapi.yaml');
export const DEFAULT_OUT = join(UI_ROOT, 'src', 'api', 'generated', 'schema.ts');

/** Module specifier of src/api/untrusted.ts as seen from src/api/generated/schema.ts. */
const UNTRUSTED_MODULE = '../untrusted';

export const HEADER = [
  '// SPDX-License-Identifier: Apache-2.0',
  '//',
  '// Generated by gen:api (scripts/gen-api.mjs) from docs/api/openapi.yaml: do not edit.',
  '// Run `pnpm gen:api` after the contract changes; `pnpm check:api` fails when this file differs',
  '// from a fresh generation. Properties marked x-argos-untrusted (collected strings, DSN-14-13)',
  '// are typed Untrusted: render them through SafeText, SafeLink or CodeBlock only (SEC-60).',
  '',
  `import type { ${UNTRUSTED_TYPE} } from '${UNTRUSTED_MODULE}';`,
  '',
  '',
].join('\n');

/**
 * @typedef {{ untrustedSchemas: number, untrustedStrings: number, propagated: number,
 *             nonString: string[] }} UntrustedStats
 *   untrustedSchemas  schemas carrying the flag (after propagation to items and values)
 *   untrustedStrings  of those, the ones with a string type: each becomes one `Untrusted`
 *   propagated        items/values that received the flag from their array or map
 *   nonString         JSON pointers of flagged schemas that are neither strings nor containers
 *                     (numbers inside a flagged map, for example); they keep their type
 */

/**
 * @param {unknown} value
 * @returns {value is Record<string, unknown>}
 */
function isObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * @param {Record<string, unknown>} schema
 * @returns {boolean} the schema is a plain string (or nullable string) without enum/const
 */
function isStringSchema(schema) {
  const { type } = schema;
  const hasString = type === 'string' || (Array.isArray(type) && type.includes('string'));
  return hasString && !('enum' in schema) && !('const' in schema);
}

/**
 * @param {Record<string, unknown>} schema
 * @returns {boolean}
 */
function isContainer(schema) {
  return isObject(schema['items']) || isObject(schema['additionalProperties']);
}

/**
 * Carries the untrusted flag of arrays and maps over to their items and values, and counts the
 * flagged schemas of the bundled document (mutates `root`). A flagged container whose items or
 * values are a $ref cannot be branded and fails the generation.
 *
 * @param {Record<string, unknown>} root `{ paths, components }` of the bundled document
 * @returns {UntrustedStats}
 */
export function prepareUntrusted(root) {
  /** @type {UntrustedStats} */
  const stats = { untrustedSchemas: 0, untrustedStrings: 0, propagated: 0, nonString: [] };
  /** @type {Set<object>} */
  const seen = new Set();

  /**
   * @param {unknown} node
   * @param {string} pointer
   */
  const visit = (node, pointer) => {
    if (Array.isArray(node)) {
      node.forEach((child, index) => {
        visit(child, `${pointer}/${String(index)}`);
      });
      return;
    }
    if (!isObject(node) || seen.has(node)) {
      return;
    }
    seen.add(node);
    if (node[UNTRUSTED_EXTENSION] === true) {
      for (const key of ['items', 'additionalProperties']) {
        const child = node[key];
        if (!isObject(child)) {
          continue;
        }
        if ('$ref' in child) {
          throw new Error(
            `${pointer}/${key}: ${UNTRUSTED_EXTENSION} on a container whose ${key} is a $ref ` +
              'cannot be branded; inline the string schema in the contract',
          );
        }
        if (child[UNTRUSTED_EXTENSION] !== true) {
          child[UNTRUSTED_EXTENSION] = true;
          stats.propagated += 1;
        }
      }
      stats.untrustedSchemas += 1;
      if (isStringSchema(node)) {
        stats.untrustedStrings += 1;
      } else if (!isContainer(node)) {
        stats.nonString.push(pointer);
      }
    }
    for (const [key, child] of Object.entries(node)) {
      visit(child, `${pointer}/${key.replaceAll('~', '~0').replaceAll('/', '~1')}`);
    }
  };
  for (const [key, value] of Object.entries(root)) {
    visit(value, `#/${key}`);
  }
  return stats;
}

/**
 * Generates the schema module text.
 *
 * @param {{ spec?: string }} [options]
 * @returns {Promise<{ text: string, stats: UntrustedStats }>}
 */
export async function generate({ spec = DEFAULT_SPEC } = {}) {
  if (!existsSync(spec)) {
    throw new Error(`${spec}: OpenAPI contract not found (./gradlew :server:generateOpenApi)`);
  }
  /** @type {UntrustedStats | null} */
  let stats = null;
  const ast = await openapiTS(pathToFileURL(spec), {
    silent: true,
    transform(schemaObject, options) {
      if (stats === null) {
        // First call: the document is bundled; flag items and values before any is transformed.
        stats = prepareUntrusted({
          paths: options.ctx.resolve('#/paths') ?? {},
          components: options.ctx.resolve('#/components') ?? {},
        });
      }
      const schema = /** @type {Record<string, unknown>} */ (/** @type {unknown} */ (schemaObject));
      // `type: [string, 'null']` is not branded here: openapi-typescript transforms each member
      // again (with type 'string'), which keeps `| null`.
      if (
        schema[UNTRUSTED_EXTENSION] === true &&
        schema['type'] === 'string' &&
        isStringSchema(schema)
      ) {
        return ts.factory.createTypeReferenceNode(UNTRUSTED_TYPE);
      }
      return undefined;
    },
  });
  const body = astToString(ast);
  // Formatted with the UI's Prettier configuration (as `prettier --check .` sees the committed
  // file, .editorconfig included), whatever --out points at.
  const formatted = await prettier.format(`${HEADER}${body}`, {
    ...(await prettier.resolveConfig(DEFAULT_OUT, { editorconfig: true })),
    filepath: DEFAULT_OUT,
  });
  const text = formatted.replaceAll('\r\n', '\n');
  return {
    text,
    stats: stats ?? { untrustedSchemas: 0, untrustedStrings: 0, propagated: 0, nonString: [] },
  };
}

/**
 * Number of `Untrusted` type references in a generated module (parsed; comments and the import
 * do not count).
 *
 * @param {string} text
 * @returns {number}
 */
export function countUntrustedReferences(text) {
  const source = ts.createSourceFile('schema.ts', text, ts.ScriptTarget.ESNext, true);
  let count = 0;
  /** @param {ts.Node} node */
  const visit = (node) => {
    if (
      ts.isTypeReferenceNode(node) &&
      ts.isIdentifier(node.typeName) &&
      node.typeName.text === UNTRUSTED_TYPE
    ) {
      count += 1;
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return count;
}

/**
 * Compares the committed module with a fresh generation.
 *
 * @param {{ spec?: string, out?: string }} [options]
 * @returns {Promise<{ ok: boolean, expected: string, actual: string | null, stats: UntrustedStats }>}
 */
export async function checkGenerated({ spec = DEFAULT_SPEC, out = DEFAULT_OUT } = {}) {
  const { text, stats } = await generate({ spec });
  const actual = existsSync(out) ? readFileSync(out, 'utf8') : null;
  return { ok: actual === text, expected: text, actual, stats };
}

/**
 * First differing line of two texts, for the check:api message.
 *
 * @param {string} expected
 * @param {string} actual
 * @returns {string}
 */
export function firstDifference(expected, actual) {
  const a = expected.split('\n');
  const b = actual.split('\n');
  const length = Math.max(a.length, b.length);
  for (let index = 0; index < length; index += 1) {
    if (a[index] !== b[index]) {
      return (
        `line ${String(index + 1)}: expected ${JSON.stringify(a[index] ?? '<end of file>')}, ` +
        `found ${JSON.stringify(b[index] ?? '<end of file>')}`
      );
    }
  }
  return 'no difference';
}

/**
 * @param {string[]} argv
 * @returns {Promise<number>} exit code
 */
export async function main(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      check: { type: 'boolean', default: false },
      spec: { type: 'string', default: DEFAULT_SPEC },
      out: { type: 'string', default: DEFAULT_OUT },
    },
    strict: true,
  });
  const spec = resolve(values.spec);
  const out = resolve(values.out);
  const shown = relative(UI_ROOT, out).replaceAll('\\', '/');
  if (values.check) {
    const result = await checkGenerated({ spec, out });
    if (result.actual === null) {
      console.error(`ERROR ${shown} does not exist; run pnpm gen:api and commit the result`);
      return 1;
    }
    if (!result.ok) {
      console.error(
        `ERROR ${shown} differs from a fresh generation (${firstDifference(result.expected, result.actual)}); ` +
          'run pnpm gen:api and commit the result (never edit it by hand)',
      );
      return 1;
    }
    console.log(
      `check:api: ${shown} is up to date (untrusted strings=${String(result.stats.untrustedStrings)})`,
    );
    return 0;
  }
  const { text, stats } = await generate({ spec });
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(
    `gen:api: wrote ${shown} (untrusted schemas=${String(stats.untrustedSchemas)}, ` +
      `strings typed ${UNTRUSTED_TYPE}=${String(stats.untrustedStrings)}, ` +
      `flag carried to items/values=${String(stats.propagated)}, ` +
      `non-string kept=${String(stats.nonString.length)})`,
  );
  return 0;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = await main(process.argv.slice(2));
}
